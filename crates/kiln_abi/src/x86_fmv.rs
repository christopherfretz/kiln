/// The word and mask of `__builtin_cpu_supports` feature `name`.
pub fn cpu_supports(name: &str) -> Option<(usize, u32)> {
    CPU_SUPPORTS.iter().find(|e| e.0 == name).map(|e| (usize::from(e.1), e.2))
}

/// The four-word `__builtin_cpu_supports` mask of `features` (LLVM
/// `getCpuSupportsMask`); unknown names add nothing.
pub fn cpu_supports_mask<'a>(features: impl IntoIterator<Item = &'a str>) -> [u32; 4] {
    let mut m = [0; 4];
    for f in features {
        if let Some((w, bit)) = cpu_supports(f) {
            m[w] |= bit;
        }
    }
    m
}

/// The FMV priority of a feature or `arch=` CPU name (0: none).
pub fn fmv_priority(name: &str) -> u32 {
    if let Some(e) = FMV_ARCHES.iter().find(|e| e.0 == name) {
        return e.1;
    }
    // The x86-64 levels, which only `target_clones` may name: their key
    // features are `sse2`, `sse4.2`, `avx2` and `avx512vl`.
    let level = match name {
        "x86-64" => Some("sse2"),
        "x86-64-v2" => Some("sse4.2"),
        "x86-64-v3" => Some("avx2"),
        "x86-64-v4" => Some("avx512vl"),
        _ => None,
    };
    if let Some(k) = level {
        return fmv_priority(k) + 1;
    }
    FMV_FEATURES.iter().find(|e| e.0 == name).map_or(0, |e| e.1 << 1)
}

/// The `__cpu_model` field and value of `__builtin_cpu_is` name `name`.
pub fn cpu_is(name: &str) -> Option<(u32, u32)> {
    CPU_IS.iter().find(|e| e.0 == name).map(|e| (u32::from(e.1), e.2))
}

/// The `cpu_specific` / `cpu_dispatch` processor `name`.
pub fn processor(name: &str) -> Option<&'static Processor> {
    PROCESSORS.iter().find(|p| p.name == name)
}
