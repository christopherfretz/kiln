/// A `cpu_specific` / `cpu_dispatch` processor.
#[derive(Clone, Copy, Debug)]
pub struct Processor {
    /// The name as written in the attribute.
    pub name: &'static str,
    /// The mangling character (`'\0'` for the processors LLVM gives none).
    pub mangling: char,
    /// Its `__builtin_cpu_supports` mask, by word.
    pub mask: [u32; 4],
    /// Its target features, comma-separated, without `+`.
    pub features: &'static str,
}

