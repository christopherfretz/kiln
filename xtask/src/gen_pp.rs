//! `cargo xtask gen-pp-corpus`: writes the generated header corpus under
//! `tests/differential/pp/` (`spec/harness.md` "Generated pp corpus"), one
//! tiny test per header that `#include`s it and is compared with clang's
//! `-E -P` token-wise.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use crate::util::header::CXX_STDS;
use crate::util::repo_root;

const USAGE: &str = "\
usage: cargo xtask gen-pp-corpus [options]

Writes one `expect: pp` test per header under tests/differential/pp/:
  libcxx/        libc++ public headers (and experimental/)
  libcxx-c/      the C headers libc++ wraps, through its <name.h> wrappers
  sysroot/       top-level <sysroot>/*.h not shadowed by a libc++ wrapper
Idempotent: unchanged files are not rewritten; stale generated files (those
carrying the GENERATED banner) are removed. See spec/harness.md.

options:
  --std <std>       -std= of the generated tests (default c++26); other than
                    c++26, the category directories get a `.<std>` suffix
  --libcxx <dir>    libc++ header directory (default /usr/lib/llvm-19/include/c++/v1)
  --sysroot <dir>   C library header directory (default /usr/include)
  --out <dir>       output directory (default <repo>/tests/differential/pp)
  --check           change nothing; exit 1 if the corpus is not up to date
  -h, --help        this text
";

/// The first line of every generated file; only files starting with it are
/// ever removed.
pub const BANNER: &str = "// GENERATED by `cargo xtask gen-pp-corpus`; do not edit.";

const DEFAULT_STD: &str = "c++26";

/// Never generated, with the reason (printed by the generator, listed in
/// `tests/differential/pp/README.md`).
const EXCLUDED_LIBCXX: &[(&str, &str)] = &[
    ("__*", "implementation-detail headers; reached through the public ones"),
    ("libcxx.imp", "include-what-you-use mapping, not a header"),
    ("module.modulemap", "clang module map, not a header"),
    ("ext/", "pre-standard GNU extensions (hash_map, hash_set), deprecated and warning"),
    ("experimental/__*", "implementation detail of experimental/"),
];
const EXCLUDED_SYSROOT: &[(&str, &str)] = &[
    ("regexp.h", "glibc's obsolete regexp.h is `#error` unconditionally"),
    ("gnumake.h", "GNU make's plugin API (package `make`), not a C library header"),
];

/// libc++ files that are headers but are not C library wrappers.
const LIBCXX_NON_C_DOT_H: &[&str] = &["cxxabi.h"];

#[derive(Debug, PartialEq, Eq)]
struct Options {
    std: String,
    libcxx: PathBuf,
    sysroot: PathBuf,
    out: Option<PathBuf>,
    check: bool,
}

fn parse_args(args: impl IntoIterator<Item = String>) -> Result<Option<Options>, String> {
    let mut o = Options {
        std: DEFAULT_STD.to_owned(),
        libcxx: PathBuf::from("/usr/lib/llvm-19/include/c++/v1"),
        sysroot: PathBuf::from("/usr/include"),
        out: None,
        check: false,
    };
    let mut it = args.into_iter();
    while let Some(arg) = it.next() {
        let (flag, inline) = match arg.split_once('=') {
            Some((f, v)) if f.starts_with("--") => (f.to_owned(), Some(v.to_owned())),
            _ => (arg.clone(), None),
        };
        let mut value = |name: &str| -> Result<String, String> {
            inline.clone().or_else(|| it.next()).ok_or_else(|| format!("`{name}` requires a value"))
        };
        match flag.as_str() {
            "-h" | "--help" => return Ok(None),
            "--std" => {
                let v = value("--std")?;
                if !CXX_STDS.contains(&v.as_str()) {
                    return Err(format!("unknown --std `{v}` (allowed: {})", CXX_STDS.join("|")));
                }
                o.std = v;
            }
            "--libcxx" => o.libcxx = PathBuf::from(value("--libcxx")?),
            "--sysroot" => o.sysroot = PathBuf::from(value("--sysroot")?),
            "--out" => o.out = Some(PathBuf::from(value("--out")?)),
            "--check" if inline.is_none() => o.check = true,
            f => return Err(format!("unknown argument `{f}`")),
        }
    }
    Ok(Some(o))
}

pub fn main(args: impl IntoIterator<Item = String>) -> ExitCode {
    let opts = match parse_args(args) {
        Ok(Some(o)) => o,
        Ok(None) => {
            print!("{USAGE}");
            return ExitCode::SUCCESS;
        }
        Err(e) => {
            eprintln!("xtask gen-pp-corpus: {e}\n\n{USAGE}");
            return ExitCode::from(2);
        }
    };
    let out = opts.out.clone().unwrap_or_else(|| repo_root().join("tests/differential/pp"));
    let plan = match plan(&opts) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("xtask gen-pp-corpus: {e}");
            return ExitCode::from(2);
        }
    };
    match apply(&out, &plan, opts.check) {
        Ok(stats) => {
            print!("{}", summary(&plan, &stats, &out, opts.check));
            if opts.check && stats.changed() {
                eprintln!("xtask gen-pp-corpus: the corpus is out of date; rerun without --check");
                return ExitCode::from(1);
            }
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("xtask gen-pp-corpus: {e}");
            ExitCode::from(2)
        }
    }
}

/// What to generate: relative path under the output directory -> content,
/// plus the category directories the generator owns for this std.
#[derive(Debug, Default)]
struct Plan {
    files: BTreeMap<PathBuf, String>,
    dirs: Vec<PathBuf>,
    /// Per category: number of tests.
    counts: BTreeMap<String, usize>,
    /// Excluded entries actually found, with reasons.
    excluded: Vec<(String, &'static str)>,
}

fn category_dir(category: &str, std: &str) -> PathBuf {
    if std == DEFAULT_STD {
        PathBuf::from(category)
    } else {
        PathBuf::from(format!("{category}.{std}"))
    }
}

/// The content of the test for `#include <header>`.
pub fn test_source(header: &str, std: &str) -> String {
    format!(
        "{BANNER}\n//@ expect: pp\n//@ std: {std}\n//@ oracle: clang\n\
         //@ args: -stdlib=libc++ -resource-dir %{{resource_dir}}\n#include <{header}>\n"
    )
}

fn sorted_entries(dir: &Path) -> Result<Vec<(String, bool)>, String> {
    let rd = fs::read_dir(dir).map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
    let mut v = Vec::new();
    for e in rd {
        let e = e.map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
        let name = e.file_name().to_string_lossy().into_owned();
        // `metadata` follows symlinks: a symlinked header is a header.
        let is_dir = fs::metadata(e.path()).is_ok_and(|m| m.is_dir());
        v.push((name, is_dir));
    }
    v.sort();
    Ok(v)
}

fn plan(o: &Options) -> Result<Plan, String> {
    let mut p = Plan::default();
    let libcxx_dir = category_dir("libcxx", &o.std);
    let c_dir = category_dir("libcxx-c", &o.std);
    let sys_dir = category_dir("sysroot", &o.std);
    p.dirs = vec![libcxx_dir.clone(), c_dir.clone(), sys_dir.clone()];
    let add = |p: &mut Plan, category: &str, rel: PathBuf, header: &str| {
        p.files.insert(rel, test_source(header, &o.std));
        *p.counts.entry(category.to_owned()).or_insert(0) += 1;
    };

    let mut wrappers = Vec::new();
    let mut seen_impl = false;
    for (name, is_dir) in sorted_entries(&o.libcxx)? {
        if name.starts_with("__") {
            seen_impl = true;
        } else if is_dir && name == "experimental" {
            for (sub, sub_dir) in sorted_entries(&o.libcxx.join("experimental"))? {
                if sub.starts_with("__") {
                    if !p.excluded.iter().any(|(e, _)| e == "experimental/__*") {
                        p.excluded.push(("experimental/__*".into(), EXCLUDED_LIBCXX[4].1));
                    }
                } else if !sub_dir {
                    let rel = libcxx_dir.join("experimental").join(format!("{sub}.cpp"));
                    add(&mut p, "libcxx/experimental", rel, &format!("experimental/{sub}"));
                }
            }
        } else if is_dir {
            let reason = if name == "ext" { EXCLUDED_LIBCXX[3].1 } else { "unknown directory" };
            p.excluded.push((format!("{name}/"), reason));
        } else if let Some((_, reason)) = EXCLUDED_LIBCXX.iter().find(|(e, _)| *e == name) {
            p.excluded.push((name, reason));
        } else if is_dot_h(&name) && !LIBCXX_NON_C_DOT_H.contains(&name.as_str()) {
            wrappers.push(name);
        } else {
            add(&mut p, "libcxx", libcxx_dir.join(format!("{name}.cpp")), &name);
        }
    }
    if seen_impl {
        p.excluded.insert(0, ("__*".into(), EXCLUDED_LIBCXX[0].1));
    }
    for w in &wrappers {
        add(&mut p, "libcxx-c", c_dir.join(format!("{w}.cpp")), w);
    }
    for (name, is_dir) in sorted_entries(&o.sysroot)? {
        if is_dir || !is_dot_h(&name) {
            continue;
        }
        if wrappers.contains(&name) {
            // Reached through the libc++ wrapper in libcxx-c/.
            continue;
        }
        if let Some((_, reason)) = EXCLUDED_SYSROOT.iter().find(|(e, _)| *e == name) {
            p.excluded.push((format!("{}/{name}", o.sysroot.display()), reason));
            continue;
        }
        add(&mut p, "sysroot", sys_dir.join(format!("{name}.cpp")), &name);
    }
    if p.counts.get("libcxx").copied().unwrap_or(0) == 0 {
        return Err(format!("no libc++ headers found in {}", o.libcxx.display()));
    }
    Ok(p)
}

#[derive(Debug, Default)]
struct Stats {
    written: usize,
    unchanged: usize,
    removed: usize,
}

impl Stats {
    fn changed(&self) -> bool {
        self.written + self.removed > 0
    }
}

/// Writes the planned files that differ and removes stale generated ones
/// in the owned directories. With `check`, only counts.
fn apply(out: &Path, plan: &Plan, check: bool) -> Result<Stats, String> {
    let mut st = Stats::default();
    for (rel, content) in &plan.files {
        let path = out.join(rel);
        if fs::read_to_string(&path).is_ok_and(|old| old == *content) {
            st.unchanged += 1;
            continue;
        }
        st.written += 1;
        if check {
            continue;
        }
        if let Some(dir) = path.parent() {
            fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
        }
        fs::write(&path, content).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    }
    for dir in &plan.dirs {
        let mut stale = Vec::new();
        find_stale(out, dir, plan, &mut stale)?;
        st.removed += stale.len();
        if !check {
            for path in stale {
                fs::remove_file(&path)
                    .map_err(|e| format!("cannot remove {}: {e}", path.display()))?;
            }
        }
    }
    Ok(st)
}

/// Generated files under `out/rel` that the plan no longer contains.
fn find_stale(out: &Path, rel: &Path, plan: &Plan, stale: &mut Vec<PathBuf>) -> Result<(), String> {
    let dir = out.join(rel);
    let Ok(rd) = fs::read_dir(&dir) else {
        return Ok(());
    };
    for e in rd {
        let e = e.map_err(|e| format!("cannot read {}: {e}", dir.display()))?;
        let child = rel.join(e.file_name());
        let path = out.join(&child);
        if path.is_dir() {
            find_stale(out, &child, plan, stale)?;
        } else if !plan.files.contains_key(&child)
            && fs::read_to_string(&path).is_ok_and(|s| s.starts_with(BANNER))
        {
            stale.push(path);
        }
    }
    Ok(())
}

fn summary(plan: &Plan, st: &Stats, out: &Path, check: bool) -> String {
    use std::fmt::Write as _;
    let mut s = String::new();
    let verb = if check { "would write" } else { "wrote" };
    let removed = if check { "would remove" } else { "removed" };
    let _ = writeln!(
        s,
        "gen-pp-corpus: {} tests in {}: {verb} {}, {} unchanged, {removed} {} stale",
        plan.files.len(),
        out.display(),
        st.written,
        st.unchanged,
        st.removed
    );
    for (cat, n) in &plan.counts {
        let _ = writeln!(s, "  {cat:<22} {n:>4}");
    }
    if !plan.excluded.is_empty() {
        let _ = writeln!(s, "excluded:");
        for (what, why) in &plan.excluded {
            let _ = writeln!(s, "  {what:<22} {why}");
        }
    }
    s
}

/// Whether `name` ends in `.h` (case-sensitively: `.H` is a C++ source).
fn is_dot_h(name: &str) -> bool {
    Path::new(name).extension().is_some_and(|e| e == "h")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn strings(v: &[&str]) -> Vec<String> {
        v.iter().map(|s| (*s).to_owned()).collect()
    }

    #[test]
    fn cli() {
        let o = parse_args(strings(&["--std=c++20", "--libcxx", "/l", "--out", "o", "--check"]))
            .unwrap()
            .unwrap();
        assert_eq!(o.std, "c++20");
        assert_eq!(o.libcxx, PathBuf::from("/l"));
        assert_eq!(o.out, Some(PathBuf::from("o")));
        assert!(o.check);
        assert!(parse_args(strings(&["--std", "c17"])).is_err());
        assert!(parse_args(strings(&["--bogus"])).is_err());
        assert_eq!(parse_args(strings(&["-h"])).unwrap(), None);
    }

    /// A fake libc++ and sysroot: categories, exclusions, std suffixes,
    /// idempotence and stale-file removal.
    #[test]
    fn generates_idempotently() {
        let base = crate::util::target_dir(&repo_root())
            .unwrap()
            .join(format!("xtask-gen-pp-test-{}", std::process::id()));
        let (lib, sys, out) = (base.join("v1"), base.join("include"), base.join("out"));
        for d in [
            lib.join("experimental/__simd"),
            lib.join("ext"),
            lib.join("__algorithm"),
            sys.join("sys"),
        ] {
            fs::create_dir_all(d).unwrap();
        }
        for f in [
            "vector",
            "map",
            "stdio.h",
            "cxxabi.h",
            "__config",
            "libcxx.imp",
            "module.modulemap",
            "experimental/simd",
            "experimental/__config",
            "ext/hash_map",
        ] {
            fs::write(lib.join(f), "").unwrap();
        }
        for f in ["stdio.h", "unistd.h", "regexp.h", "sys/types.h", "notes.txt"] {
            fs::write(sys.join(f), "").unwrap();
        }
        let opts = |std: &str| Options {
            std: std.into(),
            libcxx: lib.clone(),
            sysroot: sys.clone(),
            out: Some(out.clone()),
            check: false,
        };
        let p = plan(&opts("c++26")).unwrap();
        let names: Vec<String> =
            p.files.keys().map(|k| k.to_string_lossy().replace('\\', "/")).collect();
        assert_eq!(
            names,
            [
                "libcxx/cxxabi.h.cpp",
                "libcxx/experimental/simd.cpp",
                "libcxx/map.cpp",
                "libcxx/vector.cpp",
                "libcxx-c/stdio.h.cpp",
                "sysroot/unistd.h.cpp",
            ]
        );
        assert_eq!(
            p.files[Path::new("libcxx/experimental/simd.cpp")],
            format!(
                "{BANNER}\n//@ expect: pp\n//@ std: c++26\n//@ oracle: clang\n\
                 //@ args: -stdlib=libc++ -resource-dir %{{resource_dir}}\n\
                 #include <experimental/simd>\n"
            )
        );
        let excluded: Vec<&str> = p.excluded.iter().map(|(e, _)| e.as_str()).collect();
        assert_eq!(
            excluded[..5],
            ["__*", "experimental/__*", "ext/", "libcxx.imp", "module.modulemap"]
        );
        assert!(excluded[5].ends_with("include/regexp.h"));
        // Every generated test parses as a pp test.
        for src in p.files.values() {
            let spec = crate::test::directives::parse(src, crate::test::directives::Lang::Cxx);
            assert_eq!(spec.map(|s| s.expect), Ok(crate::test::directives::Expect::Pp), "{src}");
        }

        let st = apply(&out, &p, false).unwrap();
        assert_eq!((st.written, st.unchanged, st.removed), (6, 0, 0));
        let st = apply(&out, &p, true).unwrap();
        assert!(!st.changed());
        // A header disappears: its generated test goes, hand-written files stay.
        fs::write(out.join("libcxx/hand-written.cpp"), "int x;\n").unwrap();
        fs::remove_file(lib.join("map")).unwrap();
        let p = plan(&opts("c++26")).unwrap();
        let st = apply(&out, &p, true).unwrap();
        assert_eq!((st.written, st.unchanged, st.removed), (0, 5, 1));
        assert!(out.join("libcxx/map.cpp").exists(), "--check changes nothing");
        apply(&out, &p, false).unwrap();
        assert!(!out.join("libcxx/map.cpp").exists());
        assert!(out.join("libcxx/hand-written.cpp").exists());
        // Another std goes to sibling directories and leaves c++26 alone.
        let p20 = plan(&opts("c++20")).unwrap();
        assert!(p20.files.keys().all(|k| k.starts_with("libcxx.c++20")
            || k.starts_with("libcxx-c.c++20")
            || k.starts_with("sysroot.c++20")));
        let st = apply(&out, &p20, false).unwrap();
        assert_eq!(st.removed, 0);
        assert!(out.join("libcxx.c++20/vector.cpp").is_file());
        assert!(out.join("libcxx/vector.cpp").is_file());
        fs::remove_dir_all(&base).unwrap();
    }
}
