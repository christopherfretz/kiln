//! Console summary and the Markdown status page (`spec/libcxx.md`
//! "Report").

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::time::Duration;

use super::cluster::Clusters;
use super::run::{Outcome, Stage, TestResult};

pub const BEGIN: &str = "<!-- libcxx:begin -->";
pub const END: &str = "<!-- libcxx:end -->";

/// Outcome counts for one group of tests.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Counts {
    pub total: usize,
    pub pass: usize,
    pub fail: usize,
    pub xfail: usize,
    pub xpass: usize,
    pub unsupported: usize,
    /// Of `unsupported`, those the driver (not the configuration) refused.
    pub unsupported_driver: usize,
    pub killed: usize,
    pub timeout: usize,
    pub error: usize,
    /// `fail` split by stage.
    pub fail_stage: BTreeMap<Stage, usize>,
}

impl Counts {
    pub fn add(&mut self, o: &Outcome) {
        self.total += 1;
        match o {
            Outcome::Pass => self.pass += 1,
            Outcome::Fail(s) => {
                self.fail += 1;
                *self.fail_stage.entry(*s).or_default() += 1;
            }
            Outcome::XFail => self.xfail += 1,
            Outcome::XPass => self.xpass += 1,
            Outcome::Unsupported(r) => {
                self.unsupported += 1;
                if r.starts_with("driver:") {
                    self.unsupported_driver += 1;
                }
            }
            Outcome::Killed(_) => self.killed += 1,
            Outcome::Timeout(_) => self.timeout += 1,
            Outcome::Error(_) => self.error += 1,
        }
    }

    /// PASS over the tests that ran (total minus UNSUPPORTED), in percent.
    #[allow(clippy::cast_precision_loss)] // test counts are far below 2^52
    pub fn pass_rate(&self) -> Option<f64> {
        let ran = self.total - self.unsupported;
        (ran > 0).then(|| 100.0 * self.pass as f64 / ran as f64)
    }

    fn rate(&self) -> String {
        self.pass_rate().map_or_else(|| "—".to_owned(), |r| format!("{r:.1}%"))
    }

    pub fn summary_line(&self) -> String {
        format!(
            "{} tests: {} pass, {} fail, {} xfail, {} xpass, {} unsupported ({} driver), {} killed, {} timeout, {} error; pass rate {}",
            self.total,
            self.pass,
            self.fail,
            self.xfail,
            self.xpass,
            self.unsupported,
            self.unsupported_driver,
            self.killed,
            self.timeout,
            self.error,
            self.rate()
        )
    }
}

/// The group (one of `roots`, relative to `libcxx/test`) a test belongs to.
pub fn group_of<'a>(rel: &str, roots: &'a [String]) -> &'a str {
    roots
        .iter()
        .find(|r| r.is_empty() || rel == r.as_str() || rel.starts_with(&format!("{r}/")))
        .map_or("(other)", String::as_str)
}

/// Facts about the run for the page header.
pub struct RunInfo {
    pub kiln_version: String,
    /// The cargo profile kiln++ was built with (`--profile`), or what is
    /// known of a `--compiler` binary's.
    pub profile: String,
    pub kiln_commit: String,
    pub tests_tag: String,
    pub libcpp_version: String,
    pub target: String,
    pub command: String,
    pub compile_flags: String,
    pub link_flags: String,
    pub features: String,
    pub limits: String,
    pub rss_source: String,
    pub wall: Duration,
}

pub fn clusters_of(results: &[TestResult]) -> Clusters {
    let mut c = Clusters::default();
    for r in results {
        if matches!(r.outcome, Outcome::Fail(_)) || r.crashed {
            c.add(&r.rel, &r.keys);
        }
    }
    c
}

/// A "peak RSS" cell: the largest of `rss` over `results`, in MiB, with
/// its test, or `unavailable` when no step was measured.
#[allow(clippy::cast_precision_loss)] // KiB fits f64
fn peak_rss(
    results: &[TestResult],
    rss: fn(&TestResult) -> Option<u64>,
    what: &str,
    source: &str,
) -> String {
    results.iter().filter_map(|r| rss(r).map(|k| (k, r.rel.as_str()))).max().map_or_else(
        || "unavailable".to_owned(),
        |(k, t)| format!("{:.0} MiB ({what}, `{t}`; {source})", k as f64 / 1024.0),
    )
}

/// The generated region of the status page, markers included.
#[allow(clippy::too_many_lines)] // one straight-line document
pub fn render(
    info: &RunInfo,
    roots: &[String],
    results: &[TestResult],
    top_clusters: usize,
) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "{BEGIN}");
    let _ = writeln!(
        s,
        "<!-- generated by `cargo xtask libcxx --report`; edits inside the markers are overwritten -->\n"
    );
    let _ = writeln!(s, "### Run\n\n| | |\n|---|---|");
    for (k, v) in [
        ("kiln", format!("`{}` at commit `{}`", info.kiln_version, info.kiln_commit)),
        ("kiln build profile", format!("`{}`", info.profile)),
        ("libc++ tests", format!("`{}` (`libcxx/test`)", info.tests_tag)),
        ("libc++ headers", format!("`_LIBCPP_VERSION` {}", info.libcpp_version)),
        ("target", format!("`{}`", info.target)),
        ("command", format!("`{}`", info.command)),
        ("compile flags", format!("`{}`", info.compile_flags)),
        ("link flags", format!("`{}`", info.link_flags)),
        ("features", info.features.clone()),
        ("limits", info.limits.clone()),
        ("wall time", format!("{:.1} s", info.wall.as_secs_f64())),
        (
            "peak RSS",
            peak_rss(results, |r| r.max_rss_kb, "largest single process", &info.rss_source),
        ),
        (
            "kiln compile peak RSS",
            peak_rss(results, |r| r.compile_rss_kb, "largest compile step", &info.rss_source),
        ),
    ] {
        let _ = writeln!(s, "| {k} | {v} |");
    }

    let mut by_group: BTreeMap<&str, Counts> = BTreeMap::new();
    let mut total = Counts::default();
    for r in results {
        by_group.entry(group_of(&r.rel, roots)).or_default().add(&r.outcome);
        total.add(&r.outcome);
    }
    let _ = writeln!(
        s,
        "\n### Results by directory\n\nPass rate is PASS / (total − UNSUPPORTED). \"driver\" counts the \
         UNSUPPORTED tests the driver cannot run (for example `.sh.cpp`), as opposed to those the \
         configuration excludes (`UNSUPPORTED: c++03`).\n"
    );
    let _ = writeln!(
        s,
        "| directory | total | pass | fail | xfail | xpass | unsupported (driver) | killed | timeout | error | pass rate |\n\
         |---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"
    );
    let row = |name: &str, c: &Counts| {
        format!(
            "| {name} | {} | {} | {} | {} | {} | {} ({}) | {} | {} | {} | {} |",
            c.total,
            c.pass,
            c.fail,
            c.xfail,
            c.xpass,
            c.unsupported,
            c.unsupported_driver,
            c.killed,
            c.timeout,
            c.error,
            c.rate()
        )
    };
    let mut order: Vec<&str> = roots.iter().map(String::as_str).collect();
    if by_group.contains_key("(other)") {
        order.push("(other)");
    }
    for g in &order {
        let c = by_group.get(g).cloned().unwrap_or_default();
        let _ = writeln!(s, "{}", row(&format!("`{}`", if g.is_empty() { "." } else { g }), &c));
    }
    let _ = writeln!(s, "{}", row("**total**", &total));

    let _ = writeln!(
        s,
        "\n### Failures by stage\n\n| directory | compile | link | run | expected-fail-but-succeeded |\n|---|---:|---:|---:|---:|"
    );
    for g in &order {
        let c = by_group.get(g).cloned().unwrap_or_default();
        let st = |x| c.fail_stage.get(&x).copied().unwrap_or(0);
        let _ = writeln!(
            s,
            "| `{}` | {} | {} | {} | {} |",
            if g.is_empty() { "." } else { g },
            st(Stage::Compile),
            st(Stage::Link),
            st(Stage::Run),
            st(Stage::ExpectedFail)
        );
    }

    let _ = writeln!(
        s,
        "\n### Dominant first errors per directory\n\nThe three most common first-error clusters among each \
         directory's FAIL tests, with their test counts.\n\n| directory | clusters |\n|---|---|"
    );
    for g in &order {
        let in_group: Vec<TestResult> =
            results.iter().filter(|r| group_of(&r.rel, roots) == *g).cloned().collect();
        let c = clusters_of(&in_group);
        let top: Vec<String> = c
            .ranked()
            .into_iter()
            .filter(|(_, c)| c.first > 0)
            .take(3)
            .map(|(k, c)| format!("{} ({})", md_code(k), c.first))
            .collect();
        let _ = writeln!(
            s,
            "| `{}` | {} |",
            if g.is_empty() { "." } else { g },
            if top.is_empty() { "—".to_owned() } else { top.join("; ") }
        );
    }

    let clusters = clusters_of(results);
    let _ = writeln!(
        s,
        "\n### Error clusters\n\n{} clusters over the FAIL tests (and compiler crashes). A cluster is the \
         failing step's `error:` message with the location dropped, quoted names replaced by `'…'` and \
         numbers by `N`. \"first\" counts tests whose first error is the cluster, \"any\" tests that \
         report it anywhere. Top {}:\n",
        clusters.len(),
        top_clusters.min(clusters.len())
    );
    let _ = writeln!(
        s,
        "| # | first | any | cluster | example test | example message |\n|---:|---:|---:|---|---|---|"
    );
    for (i, (k, c)) in clusters.ranked().into_iter().take(top_clusters).enumerate() {
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | `{}` | {} |",
            i + 1,
            c.first,
            c.any,
            md_code(k),
            c.example,
            if c.raw.is_empty() { String::new() } else { md_code(&cut(&c.raw, 160)) }
        );
    }

    let _ = writeln!(s, "\n### Crashes\n");
    let mut crashes: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for r in results.iter().filter(|r| r.crashed) {
        let k = r.keys.first().map_or("crash", |k| k.0.as_str());
        crashes.entry(k).or_default().push(&r.rel);
    }
    if crashes.is_empty() {
        let _ = writeln!(s, "None.");
    } else {
        let _ = writeln!(s, "| crash | tests | examples |\n|---|---:|---|");
        let mut v: Vec<(&str, Vec<&str>)> = crashes.into_iter().collect();
        v.sort_by(|a, b| b.1.len().cmp(&a.1.len()).then(a.0.cmp(b.0)));
        for (k, tests) in v {
            let ex: Vec<String> = tests.iter().take(3).map(|t| format!("`{t}`")).collect();
            let _ = writeln!(s, "| {} | {} | {} |", md_code(k), tests.len(), ex.join(", "));
        }
    }
    let notable: Vec<&TestResult> = results
        .iter()
        .filter(|r| {
            matches!(
                r.outcome,
                Outcome::Killed(_) | Outcome::Timeout(_) | Outcome::Error(_) | Outcome::XPass
            )
        })
        .collect();
    let _ = writeln!(s, "\n### KILLED, TIMEOUT, ERROR and XPASS\n");
    if notable.is_empty() {
        let _ = writeln!(s, "None.");
    }
    for r in notable {
        let first =
            r.keys.first().map(|k| format!(": {}", md_code(&cut(&k.1, 160)))).unwrap_or_default();
        let _ = writeln!(s, "- `{}` — {}{first}", r.rel, r.outcome);
    }

    let passed_on_status: Vec<(&str, &str)> = results
        .iter()
        .filter(|r| matches!(r.outcome, Outcome::Pass | Outcome::XPass))
        .filter_map(|r| Some((r.rel.as_str(), r.first_error.as_deref()?)))
        .collect();
    let _ = writeln!(
        s,
        "\n### compile.fail tests passed on exit status\n\n{} `.compile.fail.cpp` tests without \
         clang-verify directives passed because the compile failed; their first error, for spotting a \
         wrong-reason failure (spec/libcxx.md \".compile.fail.cpp\").\n",
        passed_on_status.len()
    );
    if !passed_on_status.is_empty() {
        let _ = writeln!(s, "<details>\n\n| test | first error |\n|---|---|");
        for (rel, line) in passed_on_status {
            let _ = writeln!(s, "| `{rel}` | {} |", md_code(&cut(line, 160)));
        }
        let _ = writeln!(s, "\n</details>");
    }

    let mut reasons: BTreeMap<&str, usize> = BTreeMap::new();
    for r in results {
        if let Outcome::Unsupported(why) = &r.outcome {
            *reasons.entry(why.as_str()).or_default() += 1;
        }
    }
    let mut reasons: Vec<(&str, usize)> = reasons.into_iter().collect();
    reasons.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(b.0)));
    let _ = writeln!(s, "\n### UNSUPPORTED reasons\n\n| reason | tests |\n|---|---:|");
    for (why, n) in reasons {
        let _ = writeln!(s, "| {} | {n} |", md_code(why));
    }
    let _ = writeln!(s, "\n{END}");
    s
}

/// `text` as inline code safe inside a table cell.
fn md_code(text: &str) -> String {
    let t = text.replace('|', "\\|");
    if t.contains('`') { format!("``{t}``") } else { format!("`{t}`") }
}

fn cut(s: &str, n: usize) -> String {
    if s.chars().count() > n {
        format!("{}…", s.chars().take(n).collect::<String>())
    } else {
        s.to_owned()
    }
}

/// Replaces the generated region of `existing` (or appends one when it has
/// no markers) with `region`.
pub fn splice(existing: &str, region: &str) -> String {
    match (existing.find(BEGIN), existing.find(END)) {
        (Some(b), Some(e)) if b < e => {
            format!("{}{}{}", &existing[..b], region.trim_end(), &existing[e + END.len()..])
        }
        _ if existing.trim().is_empty() => region.to_owned(),
        _ => format!("{}\n\n{region}", existing.trim_end()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn result(rel: &str, outcome: Outcome, keys: &[&str]) -> TestResult {
        TestResult {
            rel: rel.into(),
            outcome,
            keys: keys.iter().map(|k| ((*k).to_owned(), format!("raw {k}"))).collect(),
            crashed: false,
            detail: String::new(),
            wall: Duration::ZERO,
            max_rss_kb: Some(2048),
            compile_rss_kb: Some(1024),
            first_error: None,
            pch_path: None,
        }
    }

    #[test]
    fn counting_and_groups() {
        let roots = vec!["std/a".to_owned(), "std/ab".to_owned()];
        assert_eq!(group_of("std/a/x.pass.cpp", &roots), "std/a");
        assert_eq!(group_of("std/ab/x.pass.cpp", &roots), "std/ab");
        assert_eq!(group_of("std/b/x.pass.cpp", &roots), "(other)");
        let mut c = Counts::default();
        for o in [
            Outcome::Pass,
            Outcome::Fail(Stage::Compile),
            Outcome::Unsupported("driver: -verify".into()),
            Outcome::Unsupported("UNSUPPORTED: c++03".into()),
        ] {
            c.add(&o);
        }
        assert_eq!((c.total, c.unsupported, c.unsupported_driver), (4, 2, 1));
        assert_eq!(c.pass_rate(), Some(50.0));
        assert_eq!(Counts::default().pass_rate(), None);
    }

    #[test]
    fn page() {
        let info = RunInfo {
            kiln_version: "kiln version 0.1.0".into(),
            profile: "harness".into(),
            kiln_commit: "abc1234".into(),
            tests_tag: "llvmorg-19.1.7".into(),
            libcpp_version: "190107".into(),
            target: "aarch64-unknown-linux-gnu".into(),
            command: "cargo xtask libcxx".into(),
            compile_flags: "-std=c++26".into(),
            link_flags: "-lc++abi".into(),
            features: "kiln".into(),
            limits: "8192 MiB".into(),
            rss_source: "gnu-time".into(),
            wall: Duration::from_secs(3),
        };
        let roots = vec!["std/a".to_owned()];
        let results = vec![
            result("std/a/1.pass.cpp", Outcome::Pass, &[]),
            result("std/a/2.pass.cpp", Outcome::Fail(Stage::Compile), &["compile: x '…'"]),
            result("std/a/3.pass.cpp", Outcome::Killed(Stage::Compile), &[]),
        ];
        let page = render(&info, &roots, &results, 25);
        assert!(page.starts_with(BEGIN) && page.trim_end().ends_with(END));
        assert!(
            page.contains("| `std/a` | 3 | 1 | 1 | 0 | 0 | 0 (0) | 1 | 0 | 0 | 33.3% |"),
            "{page}"
        );
        assert!(
            page.contains(
                "| 1 | 1 | 1 | `compile: x '…'` | `std/a/2.pass.cpp` | `raw compile: x '…'` |"
            ),
            "{page}"
        );
        assert!(page.contains("- `std/a/3.pass.cpp` — KILLED (compile)"), "{page}");
        assert!(page.contains("### Crashes\n\nNone."), "{page}");
        assert!(page.contains("| kiln build profile | `harness` |"), "{page}");
        assert!(
            page.contains(
                "| peak RSS | 2 MiB (largest single process, `std/a/3.pass.cpp`; gnu-time) |"
            ),
            "{page}"
        );
        assert!(
            page.contains(
                "| kiln compile peak RSS | 1 MiB (largest compile step, `std/a/3.pass.cpp`; gnu-time) |"
            ),
            "{page}"
        );
        let unmeasured: Vec<TestResult> = results
            .iter()
            .map(|r| TestResult { max_rss_kb: None, compile_rss_kb: None, ..r.clone() })
            .collect();
        let page = render(&info, &roots, &unmeasured, 25);
        assert!(page.contains("| kiln compile peak RSS | unavailable |"), "{page}");
        assert!(page.contains("| `std/a` | `compile: x '…'` (1) |"), "{page}");
    }

    #[test]
    fn splicing() {
        let region = format!("{BEGIN}\nnew\n{END}\n");
        assert_eq!(splice("", &region), region);
        assert_eq!(splice("# T\n", &region), format!("# T\n\n{region}"));
        let old = format!("# T\n\n{BEGIN}\nold\n{END}\n\n## Reading\nkept\n");
        assert_eq!(
            splice(&old, &region),
            format!("# T\n\n{BEGIN}\nnew\n{END}\n\n## Reading\nkept\n")
        );
        assert_eq!(md_code("a|b"), "`a\\|b`");
        assert_eq!(md_code("expected `;'"), "``expected `;'``");
    }
}
