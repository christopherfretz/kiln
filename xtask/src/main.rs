    #[test]
    fn sweep_never_gates() {
        let root = util::repo_root();
        let path = root.join(".github/workflows/sweep.yml");
        let yml = std::fs::read_to_string(&path).unwrap();
        // The `on:` map: its lines up to the next top-level key.
        let on: String = yml[yml.find("\non:\n").expect("an on: map") + 5..]
            .lines()
            .take_while(|l| l.is_empty() || l.starts_with([' ', '#']))
            .fold(String::new(), |mut acc, l| {
                acc.push_str(l);
                acc.push('\n');
                acc
            });
        let triggers: Vec<&str> = on
            .lines()
            .filter(|l| l.len() > 2 && l.starts_with("  ") && !l[2..].starts_with([' ', '#']))
            .map(|l| l.trim().trim_end_matches(':'))
            .collect();
        assert_eq!(triggers, ["workflow_dispatch", "push"], "{}", path.display());
        assert!(on.contains("branches: [\"sweep/**\"]"), "{}", path.display());
        for gate in ["pull_request", "merge_group"] {
            let mut code = yml.lines().filter(|l| !l.trim_start().starts_with('#'));
            assert!(!code.any(|l| l.contains(gate)), "{} names {gate}", path.display());
        }

        let (_, jobs) = workflow_jobs(&path);
        let job = |name: &str| -> String {
            let (_, b) = jobs
                .iter()
                .find(|(n, _)| n == name)
                .unwrap_or_else(|| panic!("sweep.yml has no `{name}` job"));
            // Code only: a comment may quote the old shapes.
            b.lines().filter(|l| !l.trim_start().starts_with('#')).fold(
                String::new(),
                |mut acc, l| {
                    acc.push_str(l.trim());
                    acc.push('\n');
                    acc
                },
            )
        };
        let has = |block: &str, name: &str, line: &str| {
            assert!(block.lines().any(|l| l == line), "sweep.yml job `{name}` lacks `{line}`");
        };
        let needs_matrix = |block: &str, name: &str| {
            let needs = block
                .lines()
                .find_map(|l| l.strip_prefix("needs: "))
                .unwrap_or_else(|| panic!("sweep.yml job `{name}` has no needs"));
            assert!(
                needs.trim_matches(['[', ']']).split(',').any(|n| n.trim() == "oss-matrix"),
                "sweep.yml job `{name}` does not need oss-matrix"
            );
        };

        // The g++.dg jobs are opt-in (WP-1473): the `gxx` dispatch input
        // (default false) or a `sweep/gxx-*` push, which in turn starts no
        // libc++ or OSS job; every other `sweep/` push runs those as before.
        // A release candidate's `sweep/rc-*` push runs all three (WP-1219).
        assert!(
            on.contains("      gxx:\n") && on.contains("        default: false\n"),
            "sweep.yml has no `gxx` dispatch input defaulting to false"
        );
        let gxx_push = "startsWith(github.ref, 'refs/heads/sweep/gxx-')";
        let rc_push = "startsWith(github.ref, 'refs/heads/sweep/rc-')";
        // The PGO measurement (WP-1862) is opt-in the same way: the `pgo`
        // input or a `sweep/pgo-*` push, which runs it and nothing else.
        let pgo_push = "startsWith(github.ref, 'refs/heads/sweep/pgo-')";
        for (name, input) in [("libcxx", "libcxx"), ("oss-matrix", "oss"), ("oss", "oss")] {
            has(
                &job(name),
                name,
                &format!(
                    "if: ${{{{ (github.event_name == 'push' && !{gxx_push} && !{pgo_push}) || inputs.{input} }}}}"
                ),
            );
        }
        has(
            &job("build"),
            "build",
            &format!("if: ${{{{ github.event_name != 'push' || !{pgo_push} }}}}"),
        );
        assert!(
            on.contains("      pgo:\n") && on.matches("        default: false\n").count() >= 2,
            "sweep.yml has no `pgo` dispatch input defaulting to false"
        );
        let pgo = job("pgo");
        has(
            &pgo,
            "pgo",
            &format!("if: ${{{{ (github.event_name == 'push' && {pgo_push}) || inputs.pgo }}}}"),
        );
        assert!(
            pgo.contains("cargo xtask build --pgo") && pgo.contains("pgo-train --list"),
            "sweep.yml job `pgo` does not build with --pgo and bench the held-out set"
        );
        // A failed entry fails the measurement, except an entry over its
        // `budget-time:` (a development-host budget both binaries can
        // break on a slower runner).
        assert!(
            pgo.contains("grep -vc ': over the time budget: '")
                && pgo.contains("test \"$other\" -eq 0"),
            "sweep.yml job `pgo` does not fail on a failed entry other than a time budget"
        );
        // A release candidate's hosted half runs what ships (WP-1862), and
        // says so in the artifact import-x86 reads.
        let build = job("build");
        assert!(
            build.contains("refs/heads/sweep/rc-*) pgo=--pgo ;;")
                && build.contains("cargo xtask dist $pgo ")
                && build.contains("name: kiln-build"),
            "sweep.yml job `build` does not build an RC with --pgo and upload kiln-build"
        );
        let gxx = job("gxx-dg");
        has(
            &gxx,
            "gxx-dg",
            &format!(
                "if: ${{{{ (github.event_name == 'push' && ({gxx_push} || {rc_push})) || inputs.gxx }}}}"
            ),
        );
        assert!(gxx.contains("cargo xtask gxx-dg") && gxx.contains("--shard ${{ matrix.shard }}/"));
        let gxx_summary = job("gxx-dg-summary");
        has(
            &gxx_summary,
            "gxx-dg-summary",
            "if: ${{ !cancelled() && needs.gxx-dg.result != 'skipped' }}",
        );
        // The merge expects exactly the matrix's shard count.
        let shards = gxx
            .lines()
            .find_map(|l| l.strip_prefix("shard: [")?.strip_suffix(']'))
            .expect("gxx-dg has a shard list")
            .split(',')
            .count();
        assert!(
            gxx_summary.contains(&format!("scripts/gxx-dg-compare.py merge --expect {shards} ")),
            "gxx-dg-summary's merge --expect is not the {shards} shards of gxx-dg"
        );

        // The one source: projects.toml's sweep rows and the control rule.
        let matrix = job("oss-matrix");
        has(&matrix, "oss-matrix", "projects: ${{ steps.lists.outputs.projects }}");
        has(&matrix, "oss-matrix", "compilers: ${{ steps.lists.outputs.compilers }}");
        has(&matrix, "oss-matrix", "CONTROL: ${{ github.event_name == 'push' || inputs.control }}");
        assert!(
            matrix.contains("python3 scripts/oss/projects.py list --sweep --json"),
            "oss-matrix does not list projects.toml's sweep rows"
        );
        assert!(
            matrix.contains(r#"compilers='["kiln", "clang"]'; else compilers='["kiln"]'"#),
            "oss-matrix's compilers are not kiln + clang with the control, else kiln"
        );
        let toml = std::fs::read_to_string(root.join("scripts/oss/projects.toml")).unwrap();
        let mut sweep = Vec::new();
        let mut row = "";
        for l in toml.lines() {
            if let Some(name) = l.strip_prefix('[').and_then(|l| l.strip_suffix(']')) {
                row = name;
            } else if l.trim() == "sweep = true" {
                sweep.push(row);
            }
        }
        assert!(!sweep.is_empty(), "no projects.toml row has `sweep = true`");

        // Both readers take the same outputs; nothing spells a list again.
        let oss = job("oss");
        needs_matrix(&oss, "oss");
        has(&oss, "oss", "project: ${{ fromJSON(needs.oss-matrix.outputs.projects) }}");
        has(&oss, "oss", "compiler: ${{ fromJSON(needs.oss-matrix.outputs.compilers) }}");
        let summary = job("oss-summary");
        needs_matrix(&summary, "oss-summary");
        has(
            &summary,
            "oss-summary",
            "OSS_PROJECTS: ${{ join(fromJSON(needs.oss-matrix.outputs.projects), ' ') }}",
        );
        has(
            &summary,
            "oss-summary",
            "OSS_COMPILERS: ${{ join(fromJSON(needs.oss-matrix.outputs.compilers), ',') }}",
        );
        assert!(
            summary.contains(r#"oss-report.py --root oss --expect "$OSS_COMPILERS" $OSS_PROJECTS"#),
            "the oss summary does not pass OSS_COMPILERS and OSS_PROJECTS to --expect"
        );
        // A summary that ran without every matrix pair would drop the
        // unscheduled ones silently: it runs whenever the oss jobs ran.
        has(&summary, "oss-summary", "if: ${{ !cancelled() && needs.oss.result != 'skipped' }}");
        for (name, block) in [("oss", &oss), ("oss-summary", &summary)] {
            for l in block.lines().filter(|l| l.contains("fromJSON(")) {
                assert!(
                    l.matches("fromJSON(").count()
                        == l.matches("fromJSON(needs.oss-matrix.outputs.").count(),
                    "sweep.yml job `{name}` reads a list other than oss-matrix's: `{l}`"
                );
            }
            for p in &sweep {
                assert!(
                    !block.contains(&format!(" {p} ")) && !block.contains(&format!(", {p},")),
                    "sweep.yml job `{name}` spells the sweep project {p}"
                );
            }
        }
    }

    /// A workflow's text and its jobs, each a two-space-indented `name:`
    /// line and the lines that follow it.
    fn workflow_jobs(path: &Path) -> (String, Vec<(String, String)>) {
        let yml = std::fs::read_to_string(path).unwrap();
        let jobs = &yml[yml.find("\njobs:\n").expect("a jobs: map")..];
        let mut blocks: Vec<(String, String)> = Vec::new();
        for line in jobs.lines().skip(2) {
            let top = line.len() > 2 && !line[2..].starts_with([' ', '#']);
            if line.starts_with("  ") && top {
                blocks.push((line.trim().trim_end_matches(':').to_owned(), String::new()));
            } else if let Some((_, b)) = blocks.last_mut() {
                b.push_str(line);
                b.push('\n');
            }
        }
        (yml, blocks)
    }

    /// WP-1862: the release archives are kiln's PGO build on both
    /// architectures (spec/harness.md "Dist", "PGO build"), and the job
    /// checks that build-info.txt says so.
    #[test]
    fn release_ships_pgo() {
        let path = util::repo_root().join(".github/workflows/release.yml");
        let (_, jobs) = workflow_jobs(&path);
        let (_, dist) = jobs.iter().find(|(n, _)| n == "dist").expect("release.yml job `dist`");
        let code: Vec<&str> = dist.lines().map(str::trim).filter(|l| !l.starts_with('#')).collect();
        assert!(
            code.iter().any(|l| l.starts_with("cargo xtask dist --pgo --check ")),
            "release.yml does not build `cargo xtask dist --pgo --check`"
        );
        assert!(
            !code.iter().any(|l| l.starts_with("cargo xtask dist --check")),
            "release.yml still builds a plain dist"
        );
        assert!(code.contains(&"grep -qx 'pgo: yes' \"$RUNNER_TEMP/dist/build-info.txt\""));
        assert!(dist.contains("arch: aarch64") && dist.contains("arch: x86_64"));
    }

    /// WP-1600: every job of every workflow has a `timeout-minutes`
    /// (docs/VALIDATION.md "Job timeouts"), so a hung runner fails its job
    /// instead of holding the merge queue for GitHub's six hours. A job
    /// that calls a reusable workflow (`uses:`) cannot carry one: the
    /// called workflow's jobs do.
    #[test]
    fn every_workflow_job_has_a_timeout() {
        let dir = util::repo_root().join(".github/workflows");
        let mut paths: Vec<_> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|e| e.unwrap().path())
            .filter(|p| p.extension().is_some_and(|e| e == "yml" || e == "yaml"))
            .collect();
        paths.sort();
        assert!(paths.len() >= 4, "ci, ci-lane, sweep, release in {}", dir.display());
        for path in &paths {
            let (_, jobs) = workflow_jobs(path);
            assert!(!jobs.is_empty(), "{} has no jobs", path.display());
            for (name, b) in &jobs {
                let key = |k: &str| b.lines().find_map(|l| l.strip_prefix(&format!("    {k}: ")));
                if key("uses").is_some() {
                    continue;
                }
                let t = key("timeout-minutes").unwrap_or_else(|| {
                    panic!("{} job `{name}` has no timeout-minutes", path.display())
                });
                let t: u32 = t.trim().parse().unwrap_or_else(|_| panic!("`{name}`: `{t}`"));
                assert!((1..=360).contains(&t), "{} job `{name}`: {t} minutes", path.display());
            }
        }
    }

    /// The jobs that may hold a token with more than `contents: read`
    /// (WP-1901), as `(workflow file, job id)`: publishing a draft release.
    const WRITE_JOBS: &[(&str, &str)] = &[("release.yml", "release")];

    /// WP-1901: every workflow sets a read-only default token at top
    /// level (`permissions:` then exactly `contents: read`), and only the
    /// jobs of [`WRITE_JOBS`] carry a `permissions:` block of their own.
    #[test]
    fn workflows_default_to_a_read_only_token() {
        let dir = util::repo_root().join(".github/workflows");
        let mut paths: Vec<_> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|e| e.unwrap().path())
            .filter(|p| p.extension().is_some_and(|e| e == "yml" || e == "yaml"))
            .collect();
        paths.sort();
        assert!(paths.len() >= 4);
        for path in &paths {
            let file = path.file_name().unwrap().to_str().unwrap();
            let (yml, jobs) = workflow_jobs(path);
            let head = &yml[..yml.find("\njobs:\n").unwrap()];
            assert!(
                head.contains("\npermissions:\n  contents: read\n"),
                "{file}: no top-level `permissions: contents: read`"
            );
            let block = &head[head.find("\npermissions:\n").unwrap() + 14..];
            let more = block.lines().skip(1).take_while(|l| l.starts_with("  ")).count();
            assert_eq!(more, 0, "{file}: the default token grants more than contents: read");
            for (name, b) in &jobs {
                if b.lines().any(|l| l.starts_with("    permissions:")) {
                    assert!(
                        WRITE_JOBS.contains(&(file, name.as_str())),
                        "{file} job `{name}` raises its token; list it in WRITE_JOBS"
                    );
                }
            }
        }
    }

