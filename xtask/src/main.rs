const USAGE: &str = "\
usage: cargo xtask <command>

commands:
  test        run tests/conformance, tests/differential and tests/stress through kiln
              (`cargo xtask test --help` for options; contract in spec/harness.md)
  bench       measure bench/ compile time and memory against bench/baselines
              (`cargo xtask bench --help` for options; contract in spec/bench.md)
  clang-ast   print clang 19's AST of a file in the kiln dump format (spec/ast-dump.md §6;
              `cargo xtask clang-ast --help` for options)
  diag-split  move new kiln_diag id/group rows into their area files; --check fails on
              misplaced rows (part of ci); --replay merges a pre-split branch
              (`cargo xtask diag-split --help`; spec/diag.md §2.4)
  gen-pp-corpus
              write the generated per-header preprocessor corpus under
              tests/differential/pp (`cargo xtask gen-pp-corpus --help`)
  stress      the slow robustness suites kept out of `test` and `ci`: today the libc++
              header no-crash guard, tests/header-guard (generated by
              `gen-pp-corpus --no-crash`); takes `cargo xtask test` options
  libcxx      run libc++'s own tests (llvmorg-19.1.7 libcxx/test) with kiln; --gate m3
              is the M3 gate; not part of ci (`cargo xtask libcxx --help`; contract
              in spec/libcxx.md; needs scripts/fetch-libcxx-tests.sh)
  features    check docs/status/cxx-features.md: done rows name passing tests and
              kiln's __cpp_* values match clang 22's; an M4-gate check, not part of
              ci (`cargo xtask features --help`; spec/harness.md \"Feature table\")
  jobserver   status|refill: count, or top up, the shared jobserver pool's idle tokens
              (`cargo xtask jobserver --help`; spec/harness.md \"Jobserver\")
  ci          the merge gate: diag-split --check, fmt --check, clippy -D warnings, cargo test, then the
              corpus twice: xtask test --compiler clang++-19 (the corpus self-check;
              skipped when clang++-19 is not on PATH) and xtask test with kiln; fails
              on any FAIL, XPASS, ERROR or KILLED in either (contract in spec/harness.md
              \"CI\"); a cargo step failing with error[E0463] is rerun once
              `--quick` skips the clang self-check (local iteration only)
";

fn main() -> ExitCode {
    let mut args = std::env::args().skip(1);
    match args.next().as_deref() {
        Some("test") => test::main(args),
        Some("bench") => bench::main(args),
        Some("clang-ast") => clang_ast::main(args),
        Some("diag-split") => diag_split::main(args),
        Some("gen-pp-corpus") => gen_pp::main(args),
        Some("libcxx") => libcxx::main(args),
        Some("features") => features::main(args),
        Some("stress") => stress(args),
        Some("jobserver") => jobs::main(args),
        Some("ci") => ci(args),
        _ => {
            eprint!("{USAGE}");
            ExitCode::FAILURE
        }
    }
}

/// The suites `stress` runs (`spec/harness.md` "Stress suites"), relative to
/// the repository root.
const STRESS_SUITES: &[&str] = &["tests/header-guard"];

/// `cargo xtask stress [test options]`: `xtask test` over [`STRESS_SUITES`].
fn stress(args: impl Iterator<Item = String>) -> ExitCode {
    let mut v: Vec<String> = args.collect();
    if v.iter().any(|a| a == "-h" || a == "--help") {
        print!(
            "usage: cargo xtask stress [cargo xtask test options]\n\n\
             Runs `cargo xtask test` over the slow robustness suites ({}),\n\
             which `test` and `ci` leave out. See spec/harness.md \"Stress suites\".\n",
            STRESS_SUITES.join(", ")
        );
        return ExitCode::SUCCESS;
    }
    let root = util::repo_root();
    v.extend(STRESS_SUITES.iter().map(|s| root.join(s).display().to_string()));
    test::main(v)
}

/// The compiler `ci` self-checks the conformance corpus with (`spec/harness.md`
/// "CI"): the corpus must pass with it, or the corpus itself is wrong.
const CORPUS_COMPILER: &str = "clang++-19";

const CI_USAGE: &str = "\
usage: cargo xtask ci [--quick]

  --quick     skip the clang++-19 corpus self-check (local iteration; merges
              and GitHub CI use the full form)
";

fn ci(args: impl Iterator<Item = String>) -> ExitCode {
    let mut quick = false;
    for arg in args {
        match arg.as_str() {
            "--quick" => quick = true,
            "-h" | "--help" => {
                print!("{CI_USAGE}");
                return ExitCode::SUCCESS;
            }
            _ => {
                eprint!("xtask ci: unknown argument `{arg}`\n\n{CI_USAGE}");
                return ExitCode::from(2);
            }
        }
    }
    // The diagnostic tables are split per area (spec/diag.md §2.4).
    if let Err(problems) = diag_split::check(&util::repo_root()) {
        for p in &problems {
            eprintln!("xtask ci: diag-split: {p}");
        }
        eprintln!("xtask ci: FAILED: run `cargo xtask diag-split` (spec/diag.md §2.4)");
        return ExitCode::FAILURE;
    }
    let steps: &[&[&str]] = &[
        &["fmt", "--all", "--check"],
        &["clippy", "--workspace", "--all-targets", "--", "-D", "warnings"],
        &["test", "--workspace"],
    ];
    for step in steps {
        if !ci_step(step) {
            return ExitCode::FAILURE;
        }
    }
    // The kiln++ binary the kiln-mode run tests: built here (a no-op when
    // `cargo test` above already built it), from this checkout, into
    // `$CARGO_TARGET_DIR`.
    let root = test::repo_root();
    let kiln = match test::target_dir(&root).and_then(|t| util::build_kiln(&root, &t, "ci", false))
    {
        Ok(k) => k,
        Err(e) => {
            eprintln!("xtask ci: {e}");
            return ExitCode::FAILURE;
        }
    };

    // Both corpus runs are in-process, not a re-exec of `current_exe()`: the
    // `cargo test` step above may have rebuilt and replaced this very binary
    // (its path is then "<exe> (deleted)" and the exec fails). Both always
    // run (when not skipped), so one failing does not hide the other.
    let self_check = if quick {
        test::CorpusOutcome::Skipped("--quick".to_owned())
    } else if let Err(e) = util::identify(std::path::Path::new(CORPUS_COMPILER)) {
        test::CorpusOutcome::Skipped(format!("{CORPUS_COMPILER} not runnable: {e}"))
    } else {
        ci_corpus(&format!("--compiler {CORPUS_COMPILER}"), Some(CORPUS_COMPILER.into()))
    };
    // kiln-mode always runs: kiln as the compiler, clang++-19 as the oracle
    // (and kiln's linker), so without clang it fails rather than passing
    // unchecked.
    let kiln_mode = ci_corpus(&format!("--compiler {}", kiln.display()), Some(kiln));

    let runs = [("clang++-19 self-check", self_check), ("kiln", kiln_mode)];
    for (name, run) in &runs {
        eprintln!("xtask ci: corpus ({name}): {}", run.line());
    }
    let outcomes: Vec<test::CorpusOutcome> = runs.into_iter().map(|(_, r)| r).collect();
    if test::ci_corpus_passes(&outcomes) {
        ExitCode::SUCCESS
    } else {
        eprintln!(
            "xtask ci: FAILED: a corpus run has a FAIL, XPASS, ERROR or KILLED, or could not \
             run (see above)"
        );
        ExitCode::FAILURE
    }
}

/// One `cargo xtask test` run over the default corpus, with `compiler`.
fn ci_corpus(what: &str, compiler: Option<std::path::PathBuf>) -> test::CorpusOutcome {
    eprintln!("xtask ci: cargo xtask test {what}");
    let opts = test::Options { compiler, ..test::Options::default() };
    let start = std::time::Instant::now();
    let run = test::execute(&opts);
    if let Err(e) = &run {
        eprintln!("xtask test: error: {e}");
    }
    test::CorpusOutcome::of(&run, start.elapsed())
}

/// Runs `cargo <step>`, echoing its stderr while scanning it, and reruns it
/// once when it failed with `error[E0463]` ([`test::ci_should_retry`]).
fn ci_step(step: &[&str]) -> bool {
    let shown = step.join(" ");
    let mut retried = false;
    loop {
        eprintln!("xtask ci: cargo {shown}");
        let mut cmd = std::process::Command::new(env!("CARGO"));
        cmd.args(step).stderr(std::process::Stdio::piped());
        let (status, stderr) = match run_teeing_stderr(&mut cmd) {
            Ok(r) => r,
            Err(e) => {
                eprintln!("xtask ci: could not run cargo {shown}: {e}");
                return false;
            }
        };
        if status.success() {
            return true;
        }
        if test::ci_should_retry(&stderr, retried) {
            eprintln!(
                "xtask ci: [retry] cargo {shown} failed with error[E0463] (can't find crate: an \
                 artifact vanished mid-build); rerunning it once"
            );
            retried = true;
            continue;
        }
        eprintln!("xtask ci: failed with {status}");
        return false;
    }
}

/// Runs `cmd` (stderr piped), copying its stderr to ours as it arrives and
/// returning it with the exit status.
fn run_teeing_stderr(
    cmd: &mut std::process::Command,
) -> std::io::Result<(std::process::ExitStatus, String)> {
    use std::io::{BufRead as _, Write as _};
    let mut child = cmd.spawn()?;
    let mut captured = Vec::new();
    if let Some(pipe) = child.stderr.take() {
        let mut reader = std::io::BufReader::new(pipe);
        let mut line = Vec::new();
        let mut out = std::io::stderr();
        loop {
            line.clear();
            match reader.read_until(b'\n', &mut line) {
                Ok(0) | Err(_) => break,
                Ok(_) => {
                    let _ = out.write_all(&line);
                    captured.extend_from_slice(&line);
                }
            }
        }
    }
    let status = child.wait()?;
    Ok((status, String::from_utf8_lossy(&captured).into_owned()))
}
