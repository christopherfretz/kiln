fn main() -> ExitCode {
    let mut args = std::env::args().skip(1);
    match args.next().as_deref() {
        Some("test") => test::main(args),
        Some("bench") => bench::main(args),
        Some("clang-ast") => clang_ast::main(args),
        Some("diag-split") => diag_split::main(args),
        Some("gen-pp-corpus") => gen_pp::main(args),
        Some("gen-reflect") => gen_reflect::main(args),
        Some("libcxx") => libcxx::main(args),
        Some("libstdcxx") => libstdcxx::main(args),
        Some("features") => features::main(args),
        Some("stress") => stress(args),
        Some("jobserver") => jobs::main(args),
        Some("ci") => ci(args),
        _ => {
            eprint!("{USAGE}");
            ExitCode::FAILURE
        }
    }
}

/// The suites `stress` runs (`spec/harness.md` "Stress suites"), relative to
/// the repository root.
const STRESS_SUITES: &[&str] = &["tests/header-guard"];

/// `cargo xtask stress [test options]`: `xtask test` over [`STRESS_SUITES`].
fn stress(args: impl Iterator<Item = String>) -> ExitCode {
    let mut v: Vec<String> = args.collect();
    if v.iter().any(|a| a == "-h" || a == "--help") {
        print!(
            "usage: cargo xtask stress [cargo xtask test options]\n\n\
             Runs `cargo xtask test` over the slow robustness suites ({}),\n\
             which `test` and `ci` leave out. See spec/harness.md \"Stress suites\".\n",
            STRESS_SUITES.join(", ")
        );
        return ExitCode::SUCCESS;
    }
    let root = util::repo_root();
    v.extend(STRESS_SUITES.iter().map(|s| root.join(s).display().to_string()));
    test::main(v)
}

const CI_USAGE: &str = "\
usage: cargo xtask ci [--quick] [--oracle-only]

  --quick        skip the clang++-N corpus self-check (N: KILN_ORACLE, default 22;
                 local iteration; merges and GitHub CI use the full form)
  --oracle-only  run only what depends on the oracle release: no diag-split or
                 spec/landed lint, no fmt or clippy, and of `cargo test` only the
                 targets that read KILN_ORACLE; the corpus runs as usual (GitHub CI's
                 `KILN_ORACLE=19 cargo xtask ci --quick --oracle-only`)

KILN_REQUIRE_GCC=1: no usable GCC oracle (KILN_GCC, else g++-16) is an error
(exit 2) before any step runs (spec/harness.md \"GCC oracle\").
";

/// The cargo test targets whose outcome depends on `KILN_ORACLE`, as
/// `(package, integration test)`: all that `ci --oracle-only` runs of
/// `cargo test` (spec/harness.md "CI"). Every other unit and integration
/// test pins its tools (`clang++-19`, `/usr/lib/llvm-19`) or uses none, so a
/// second run under another oracle repeats it unchanged. The test
/// `oracle_tests_are_listed` fails when a file under `crates/` reads the
/// variable without being listed here.
const ORACLE_TESTS: &[(&str, &str)] = &[("kiln_codegen", "ir_vs_clang")];

/// The `cargo` steps of `ci` before the corpus runs, in order.
fn ci_cargo_steps(oracle_only: bool) -> Vec<Vec<&'static str>> {
    if oracle_only {
        return ORACLE_TESTS
            .iter()
            .map(|&(pkg, test)| vec!["test", "-p", pkg, "--test", test])
            .collect();
    }
    vec![
        vec!["fmt", "--all", "--check"],
        vec!["clippy", "--workspace", "--all-targets", "--", "-D", "warnings"],
        vec!["test", "--workspace"],
    ]
}

fn ci(args: impl Iterator<Item = String>) -> ExitCode {
    let mut quick = false;
    let mut oracle_only = false;
    for arg in args {
        match arg.as_str() {
            "--quick" => quick = true,
            "--oracle-only" => oracle_only = true,
            "-h" | "--help" => {
                print!("{CI_USAGE}");
                return ExitCode::SUCCESS;
            }
            _ => {
                eprint!("xtask ci: unknown argument `{arg}`\n\n{CI_USAGE}");
                return ExitCode::from(2);
            }
        }
    }
    // The compiler `ci` self-checks the conformance corpus with
    // (`spec/harness.md` "CI"): the corpus must pass with it, or the corpus
    // itself is wrong. A bad `KILN_ORACLE` fails before anything runs.
    let corpus_compiler = match oracle::Oracle::from_env() {
        Ok(o) => o.clang(),
        Err(e) => {
            eprintln!("xtask ci: {e}");
            return ExitCode::from(2);
        }
    };
    // `KILN_REQUIRE_GCC=1` (GitHub CI): no GCC oracle fails here, before the
    // cargo steps, rather than after them in the corpus runs.
    let require_gcc = oracle::require_gcc_from_env();
    if let Err(e) = test::gcc_oracle(&test::Options { require_gcc, ..test::Options::default() }) {
        eprintln!("xtask ci: {e}");
        return ExitCode::from(2);
    }
    if !oracle_only && !ci_lints(&util::repo_root()) {
        return ExitCode::FAILURE;
    }
    for step in ci_cargo_steps(oracle_only) {
        if !ci_step(&step) {
            return ExitCode::FAILURE;
        }
    }
    // The kiln++ binary the kiln-mode run tests: built here (a no-op when
    // `cargo test` above already built it), from this checkout, into
    // `$CARGO_TARGET_DIR`.
    let root = test::repo_root();
    let kiln = match test::target_dir(&root).and_then(|t| util::build_kiln(&root, &t, "ci", false))
    {
        Ok(k) => k,
        Err(e) => {
            eprintln!("xtask ci: {e}");
            return ExitCode::FAILURE;
        }
    };

    // Both corpus runs are in-process, not a re-exec of `current_exe()`: the
    // `cargo test` step above may have rebuilt and replaced this very binary
    // (its path is then "<exe> (deleted)" and the exec fails). Both always
    // run (when not skipped), so one failing does not hide the other.
    let self_check = if quick {
        test::CorpusOutcome::Skipped("--quick".to_owned())
    } else if let Err(e) = util::identify(std::path::Path::new(&corpus_compiler)) {
        test::CorpusOutcome::Skipped(format!("{corpus_compiler} not runnable: {e}"))
    } else {
        ci_corpus(
            &format!("--compiler {corpus_compiler}"),
            Some(corpus_compiler.clone().into()),
            require_gcc,
        )
    };
    // kiln-mode always runs: kiln as the compiler, clang++-N as the oracle
    // (and kiln's linker), so without clang it fails rather than passing
    // unchecked.
    let kiln_mode = ci_corpus(&format!("--compiler {}", kiln.display()), Some(kiln), require_gcc);

    let self_check_name = format!("{corpus_compiler} self-check");
    let runs = [(self_check_name.as_str(), self_check), ("kiln", kiln_mode)];
    for (name, run) in &runs {
        eprintln!("xtask ci: corpus ({name}): {}", run.line());
    }
    let outcomes: Vec<test::CorpusOutcome> = runs.into_iter().map(|(_, r)| r).collect();
    if test::ci_corpus_passes(&outcomes) {
        ExitCode::SUCCESS
    } else {
        eprintln!(
            "xtask ci: FAILED: a corpus run has a FAIL, XPASS, ERROR or KILLED, or could not \
             run (see above)"
        );
        ExitCode::FAILURE
    }
}

/// Step 0 of `ci`, in-process: the diagnostic tables are split per area
/// (spec/diag.md §2.4) and the per-WP Landed spec files are well formed
/// (spec/README.md "Landed sections"). Both report every problem before
/// failing.
fn ci_lints(root: &std::path::Path) -> bool {
    let mut ok = true;
    if let Err(problems) = diag_split::check(root) {
        for p in &problems {
            eprintln!("xtask ci: diag-split: {p}");
        }
        eprintln!("xtask ci: FAILED: run `cargo xtask diag-split` (spec/diag.md §2.4)");
        ok = false;
    }
    if let Err(problems) = landed::check(root) {
        for p in &problems {
            eprintln!("xtask ci: spec/landed: {p}");
        }
        eprintln!("xtask ci: FAILED: fix the files above (spec/README.md \"Landed sections\")");
        ok = false;
    }
    ok
}

/// One `cargo xtask test` run over the default corpus, with `compiler`
/// (`require_gcc`: `KILN_REQUIRE_GCC=1`).
fn ci_corpus(
    what: &str,
    compiler: Option<std::path::PathBuf>,
    require_gcc: bool,
) -> test::CorpusOutcome {
    eprintln!("xtask ci: cargo xtask test {what}");
    let opts = test::Options { compiler, require_gcc, ..test::Options::default() };
    let start = std::time::Instant::now();
    let run = test::execute(&opts);
    if let Err(e) = &run {
        eprintln!("xtask test: error: {e}");
    }
    test::CorpusOutcome::of(&run, start.elapsed())
}

/// Runs `cargo <step>`, echoing its stderr while scanning it, and reruns it
/// once when it failed with `error[E0463]` ([`test::ci_should_retry`]). The
/// step is in the live-children table, so a SIGINT/SIGTERM to xtask stops
/// cargo and its rustc and test processes too ([`util::process::run_step`]).
fn ci_step(step: &[&str]) -> bool {
    let shown = step.join(" ");
    let mut retried = false;
    loop {
        eprintln!("xtask ci: cargo {shown}");
        let mut cmd = std::process::Command::new(env!("CARGO"));
        cmd.args(step);
        let (status, stderr) = match util::process::run_step(&mut cmd, true) {
            Ok(r) => r,
            Err(e) => {
                eprintln!("xtask ci: could not run cargo {shown}: {e}");
                return false;
            }
        };
        if status.success() {
            return true;
        }
        if test::ci_should_retry(&stderr, retried) {
            eprintln!(
                "xtask ci: [retry] cargo {shown} failed with error[E0463] (can't find crate: an \
                 artifact vanished mid-build); rerunning it once"
            );
            retried = true;
            continue;
        }
        eprintln!("xtask ci: failed with {status}");
        return false;
    }
}

#[cfg(test)]
mod ci_tests {
    use super::{ORACLE_TESTS, ci_cargo_steps, util};
    use std::path::{Path, PathBuf};

    fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
        for e in std::fs::read_dir(dir).unwrap().filter_map(Result::ok) {
            let p = e.path();
            if p.is_dir() {
                rust_files(&p, out);
            } else if p.extension().is_some_and(|x| x == "rs") {
                out.push(p);
            }
        }
    }

    /// spec/harness.md "CI": `ci --oracle-only` runs every cargo test target
    /// that reads `KILN_ORACLE`, so a new oracle-dependent test cannot
    /// silently drop out of the second-oracle gate. A file that reads it
    /// must be an integration test listed in [`ORACLE_TESTS`] (or a module
    /// of one, `tests/<name>/…`).
    #[test]
    fn oracle_tests_are_listed() {
        let crates = util::repo_root().join("crates");
        let mut files = Vec::new();
        rust_files(&crates, &mut files);
        files.sort();
        let mut unlisted = Vec::new();
        let mut seen = std::collections::BTreeSet::new();
        for f in &files {
            if !std::fs::read_to_string(f).unwrap().contains("KILN_ORACLE") {
                continue;
            }
            let rel = f.strip_prefix(&crates).unwrap();
            let parts: Vec<&str> = rel.iter().filter_map(|c| c.to_str()).collect();
            let target = match parts[..] {
                [pkg, "tests", file] => file.strip_suffix(".rs").map(|t| (pkg, t)),
                [pkg, "tests", dir, ..] => Some((pkg, dir)),
                _ => None,
            };
            match target.filter(|t| ORACLE_TESTS.contains(t)) {
                Some(t) => _ = seen.insert(t),
                None => unlisted.push(rel.display().to_string()),
            }
        }
        assert!(
            unlisted.is_empty(),
            "these files read KILN_ORACLE but `ci --oracle-only` does not run them; add their \
             test target to ORACLE_TESTS in xtask/src/main.rs: {unlisted:?}"
        );
        for t in ORACLE_TESTS {
            assert!(seen.contains(t), "ORACLE_TESTS lists {t:?}, which does not read KILN_ORACLE");
        }
    }

    #[test]
    fn cargo_steps() {
        assert_eq!(
            ci_cargo_steps(true),
            [["test", "-p", "kiln_codegen", "--test", "ir_vs_clang"]],
            "--oracle-only"
        );
        let full = ci_cargo_steps(false);
        assert_eq!(full.len(), 3);
        assert_eq!(full[2], ["test", "--workspace"]);
    }
}
