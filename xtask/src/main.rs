/// The cargo test targets whose outcome depends on `KILN_ORACLE`, as
/// `(package, integration test)`: all that `ci --oracle-only` runs of
/// `cargo test` (spec/harness.md "CI"). Every other unit and integration
/// test pins its tools (`clang++-19`, `/usr/lib/llvm-19`) or uses none, so a
/// second run under another oracle repeats it unchanged. The test
/// `oracle_tests_are_listed` fails when a file under `crates/` reads the
/// variable without being listed here.
const ORACLE_TESTS: &[(&str, &str)] = &[("kiln_codegen", "ir_vs_clang")];

/// The unit-test groups of GitHub CI's fan-out (`ci --step unit
/// --unit-group <name>`, spec/harness.md "CI"): each named group is
/// `cargo test` of its packages, and [`UNIT_REST`] is the workspace without
/// all of them, so a new crate lands in `rest` and the groups always cover
/// exactly `cargo test --workspace`. The split balances run time (WP-692):
/// xtask's own tests (the seed-corpus run, about 75 s) and `kiln_codegen`'s
/// clang-differential tests are each about as long as all the rest.
/// `.github/workflows/ci-lane.yml` lists the same names
/// (`ci_tests::workflow_lists_the_unit_groups`).
const UNIT_GROUPS: &[(&str, &[&str])] = &[("xtask", &["xtask"]), ("codegen", &["kiln_codegen"])];

/// The Itanium mangling differential (`crates/kiln_codegen/tests/
/// mangle_vs_clang.rs`, WP-980) as `(package, test target, test name)`.
/// The unit step runs it as a step of its own, after the package's other
/// tests (which `--skip` it), with `--nocapture`, so its per-triple file and
/// symbol counts reach the log (WP-1034, spec/harness.md "The mangling
/// differential"); under `KILN_REQUIRE_LLVM=1` a missing `clang++-19` fails
/// it instead of skipping it.
const MANGLE_TEST: (&str, &str, &str) =
    ("kiln_codegen", "mangle_vs_clang", "mangling_matches_clang");

/// The unit group of every workspace package no [`UNIT_GROUPS`] entry names.
const UNIT_REST: &str = "rest";

/// The steps `ci --step` selects, in the order `ci` runs them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum CiStep {
    Lints,
    Unit,
    SelfCheck,
    Kiln,
}

impl CiStep {
    const ALL: [Self; 4] = [Self::Lints, Self::Unit, Self::SelfCheck, Self::Kiln];

    fn name(self) -> &'static str {
        match self {
            Self::Lints => "lints",
            Self::Unit => "unit",
            Self::SelfCheck => "self-check",
            Self::Kiln => "kiln",
        }
    }
}

/// The parsed `cargo xtask ci` command line.
#[derive(Clone, Debug, PartialEq, Eq)]
#[allow(clippy::struct_excessive_bools)] // independent command-line switches
struct CiArgs {
    quick: bool,
    oracle_only: bool,
    /// `--step`, indexed like [`CiStep::ALL`]; all `true` without the flag.
    steps: [bool; 4],
    shard: Option<test::Shard>,
    unit_group: Option<String>,
}

impl CiArgs {
    fn runs(&self, step: CiStep) -> bool {
        self.steps[step as usize]
    }
}

/// Parses `ci`'s arguments; `Ok(None)` is `--help`.
fn parse_ci_args(args: impl IntoIterator<Item = String>) -> Result<Option<CiArgs>, String> {
    let mut quick = false;
    let mut oracle_only = false;
    let mut steps: Option<[bool; 4]> = None;
    let mut shard = None;
    let mut unit_group = None;
    let mut it = args.into_iter();
    while let Some(arg) = it.next() {
        let (flag, inline) = match arg.split_once('=') {
            Some((f, v)) if f.starts_with("--") => (f.to_owned(), Some(v.to_owned())),
            _ => (arg.clone(), None),
        };
        let mut value = |name: &str| -> Result<String, String> {
            inline.clone().or_else(|| it.next()).ok_or_else(|| format!("`{name}` requires a value"))
        };
        match flag.as_str() {
            "--quick" if inline.is_none() => quick = true,
            "--oracle-only" if inline.is_none() => oracle_only = true,
            "-h" | "--help" => return Ok(None),
            "--step" => {
                let v = value("--step")?;
                let selected = steps.get_or_insert([false; 4]);
                for name in v.split(',') {
                    let step = CiStep::ALL.into_iter().find(|s| s.name() == name.trim());
                    let step = step.ok_or_else(|| {
                        format!("unknown --step `{name}` (lints, unit, self-check, kiln)")
                    })?;
                    selected[step as usize] = true;
                }
            }
            "--shard" => shard = Some(test::Shard::parse(&value("--shard")?)?),
            "--unit-group" => {
                let v = value("--unit-group")?;
                if v != UNIT_REST && !UNIT_GROUPS.iter().any(|&(g, _)| g == v) {
                    return Err(format!("unknown --unit-group `{v}` ({})", unit_group_names()));
                }
                unit_group = Some(v);
            }
            _ => return Err(format!("unknown argument `{arg}`")),
        }
    }
    let args = CiArgs { quick, oracle_only, steps: steps.unwrap_or([true; 4]), shard, unit_group };
    if args.shard.is_some() && !args.runs(CiStep::SelfCheck) && !args.runs(CiStep::Kiln) {
        return Err("`--shard` needs a corpus step (`--step self-check` or `kiln`)".into());
    }
    if args.unit_group.is_some() && (!args.runs(CiStep::Unit) || args.oracle_only) {
        return Err("`--unit-group` needs `--step unit` and not `--oracle-only`".into());
    }
    Ok(Some(args))
}

/// `xtask, codegen, rest`: the `--unit-group` values.
fn unit_group_names() -> String {
    let mut names: Vec<&str> = UNIT_GROUPS.iter().map(|&(g, _)| g).collect();
    names.push(UNIT_REST);
    names.join(", ")
}

/// The `cargo` commands of the `lints` step after the in-process lints.
fn ci_lint_steps() -> Vec<Vec<String>> {
    [
        &["fmt", "--all", "--check"][..],
        &["clippy", "--workspace", "--all-targets", "--", "-D", "warnings"],
    ]
    .iter()
    .map(|s| s.iter().map(|&a| a.to_owned()).collect())
    .collect()
}

/// The `cargo` commands of the `unit` step: `cargo test --workspace`, or one
/// [`UNIT_GROUPS`] group of it, or under `--oracle-only` the
/// [`ORACLE_TESTS`] targets. When the selection includes the
/// [`MANGLE_TEST`] package, the differential is split out into a second,
/// `--nocapture` command.
fn ci_unit_steps(oracle_only: bool, group: Option<&str>) -> Vec<Vec<String>> {
    let own = |v: &[&str]| v.iter().map(|&a| a.to_owned()).collect::<Vec<String>>();
    if oracle_only {
        return ORACLE_TESTS
            .iter()
            .map(|&(pkg, t)| own(&["test", "-p", pkg, "--test", t]))
            .collect();
    }
    let mut step = own(&["test"]);
    let named = group.and_then(|g| UNIT_GROUPS.iter().find(|&&(name, _)| name == g));
    if let Some((_, pkgs)) = named {
        for p in *pkgs {
            step.extend(own(&["-p", p]));
        }
    } else {
        // The whole workspace, or `rest`: the workspace without the groups.
        step.push("--workspace".into());
        if group.is_some() {
            for p in UNIT_GROUPS.iter().flat_map(|&(_, pkgs)| pkgs) {
                step.extend(own(&["--exclude", p]));
            }
        }
    }
    let (pkg, target, name) = MANGLE_TEST;
    let has_mangle = match named {
        Some((_, pkgs)) => pkgs.contains(&pkg),
        None => group.is_none(),
    };
    if !has_mangle {
        return vec![step];
    }
    step.extend(own(&["--", "--skip", name]));
    vec![step, own(&["test", "-p", pkg, "--test", target, "--", "--nocapture"])]
}

/// `cargo xtask ci`: the steps, then the total time (also after a failed
/// step).
fn ci(args: impl Iterator<Item = String>) -> ExitCode {
    let start = std::time::Instant::now();
    let code = ci_steps(args);
    eprintln!("xtask ci: total: {:.1}s", start.elapsed().as_secs_f64());
    code
}

#[allow(clippy::too_many_lines, reason = "one linear sequence of gate steps")]
fn ci_steps(args: impl Iterator<Item = String>) -> ExitCode {
    let usage = CI_USAGE.replace("{groups}", &unit_group_names());
    let args = match parse_ci_args(args) {
        Ok(Some(a)) => a,
        Ok(None) => {
            print!("{usage}");
            return ExitCode::SUCCESS;
        }
        Err(e) => {
            eprint!("xtask ci: {e}\n\n{usage}");
            return ExitCode::from(2);
        }
    };
    // The compiler `ci` self-checks the conformance corpus with
    // (`spec/harness.md` "CI"): the corpus must pass with it, or the corpus
    // itself is wrong. A bad `KILN_ORACLE` fails before anything runs.
    let corpus_compiler = match oracle::Oracle::from_env() {
        Ok(o) => o.clang(),
        Err(e) => {
            eprintln!("xtask ci: {e}");
            return ExitCode::from(2);
        }
    };
    // `KILN_REQUIRE_GCC=1` (GitHub CI): no GCC oracle fails here, before the
    // cargo steps, rather than after them in the corpus runs.
    let require_gcc = oracle::require_gcc_from_env();
    if let Err(e) = test::gcc_oracle(&test::Options { require_gcc, ..test::Options::default() }) {
        eprintln!("xtask ci: {e}");
        return ExitCode::from(2);
    }
    let skipped = |step: CiStep| eprintln!("xtask ci: {}: skipped (--step)", step.name());
    if !args.runs(CiStep::Lints) {
        skipped(CiStep::Lints);
    } else if args.oracle_only {
        eprintln!("xtask ci: lints: skipped (--oracle-only)");
    } else {
        let start = std::time::Instant::now();
        if !ci_lints(&util::repo_root()) || !ci_lint_steps().iter().all(|s| ci_step(s)) {
            return ExitCode::FAILURE;
        }
        eprintln!("xtask ci: lints: done in {:.1}s", start.elapsed().as_secs_f64());
    }
    if args.runs(CiStep::Unit) {
        let start = std::time::Instant::now();
        if !ci_unit_steps(args.oracle_only, args.unit_group.as_deref()).iter().all(|s| ci_step(s)) {
            return ExitCode::FAILURE;
        }
        eprintln!("xtask ci: unit: done in {:.1}s", start.elapsed().as_secs_f64());
    } else {
        skipped(CiStep::Unit);
    }
    // The kiln++ binary the kiln-mode run tests: built here (a no-op when
    // `cargo test` above already built it), from this checkout, into
    // `$CARGO_TARGET_DIR`.
    let kiln = if args.runs(CiStep::Kiln) {
        let root = test::repo_root();
        let start = std::time::Instant::now();
        match test::target_dir(&root).and_then(|t| util::build_kiln(&root, &t, "ci", false)) {
            Ok(k) => {
                eprintln!("xtask ci: kiln built in {:.1}s", start.elapsed().as_secs_f64());
                Some(k)
            }
            Err(e) => {
                eprintln!("xtask ci: {e}");
                return ExitCode::FAILURE;
            }
        }
    } else {
        None
    };

    // Both corpus runs are in-process, not a re-exec of `current_exe()`: the
    // `cargo test` step above may have rebuilt and replaced this very binary
    // (its path is then "<exe> (deleted)" and the exec fails). Both always
    // run (when not skipped), so one failing does not hide the other.
    let self_check = if !args.runs(CiStep::SelfCheck) {
        test::CorpusOutcome::Skipped("--step".to_owned())
    } else if args.quick {
        test::CorpusOutcome::Skipped("--quick".to_owned())
    } else if let Err(e) = util::identify(std::path::Path::new(&corpus_compiler)) {
        test::CorpusOutcome::Skipped(format!("{corpus_compiler} not runnable: {e}"))
    } else {
        ci_corpus(
            &format!("--compiler {corpus_compiler}"),
            Some(corpus_compiler.clone().into()),
            require_gcc,
            args.shard,
            None,
        )
    };
    // kiln-mode always runs unless `--step` leaves it out: kiln as the
    // compiler, clang++-N as the oracle (and kiln's linker), so without
    // clang it fails rather than passing unchecked.
    let kiln_mode = match &kiln {
        Some(kiln) => ci_corpus(
            &format!("--compiler {}", kiln.display()),
            Some(kiln.clone()),
            require_gcc,
            args.shard,
            None,
        ),
        None => test::CorpusOutcome::Skipped("--step".to_owned()),
    };
    // The module-file kind variant (spec/harness.md "Module-file kinds"):
    // every `module:` test again, kiln two-step, under each kind.
    // Then kind 2 with `--bmi-image` (WP-1828): the units the
    // declaration image covers are imported through it.
    let bmi_kind = |k: u8, image: bool| match &kiln {
        Some(kiln) => ci_corpus(
            &format!(
                "--compiler {} --bmi-kind {k}{}",
                kiln.display(),
                if image { " --bmi-image" } else { "" }
            ),
            Some(kiln.clone()),
            require_gcc,
            args.shard,
            Some((k, image)),
        ),
        None => test::CorpusOutcome::Skipped("--step".to_owned()),
    };
    let (bmi1, bmi2, bmi_image) = (bmi_kind(1, false), bmi_kind(2, false), bmi_kind(2, true));
    // The PCH differential's slice (spec/harness.md "PCH differential"):
    // the replay fallback and the snapshot, kiln only.
    let pch_diff = |m: util::pch_diff::PchDiff| match &kiln {
        Some(kiln) if !args.oracle_only => ci_pch_diff(kiln, m, args.shard),
        Some(_) => test::CorpusOutcome::Skipped("--oracle-only".to_owned()),
        None => test::CorpusOutcome::Skipped("--step".to_owned()),
    };
    let pch_replay = pch_diff(util::pch_diff::PchDiff::Replay);
    // The snapshot (WP-1395), with `--pch-diff-require-restore`: a
    // consumer that stops restoring fails CI.
    let pch_snapshot = pch_diff(util::pch_diff::PchDiff::Snapshot);

    let shard = args.shard.map_or_else(String::new, |s| format!(", shard {s}"));
    let self_check_name = format!("{corpus_compiler} self-check{shard}");
    let kiln_name = format!("kiln{shard}");
    let bmi1_name = format!("kiln --bmi-kind 1{shard}");
    let bmi2_name = format!("kiln --bmi-kind 2{shard}");
    let bmi_image_name = format!("kiln --bmi-kind 2 --bmi-image{shard}");
    let pch_replay_name = format!("kiln --pch-diff replay{shard}");
    let pch_snapshot_name =
        format!("kiln --pch-diff snapshot --pch-diff-require-restore --pch-diff-extra-dir{shard}");
    let runs = [
        (self_check_name.as_str(), self_check),
        (kiln_name.as_str(), kiln_mode),
        (bmi1_name.as_str(), bmi1),
        (bmi2_name.as_str(), bmi2),
        (bmi_image_name.as_str(), bmi_image),
        (pch_replay_name.as_str(), pch_replay),
        (pch_snapshot_name.as_str(), pch_snapshot),
    ];
    for (name, run) in &runs {
        eprintln!("xtask ci: corpus ({name}): {}", run.line());
    }
    let outcomes: Vec<test::CorpusOutcome> = runs.into_iter().map(|(_, r)| r).collect();
    if test::ci_corpus_passes(&outcomes) {
        ExitCode::SUCCESS
    } else {
        eprintln!(
            "xtask ci: FAILED: a corpus run has a FAIL, XPASS, ERROR or KILLED, or could not \
             run (see above)"
        );
        ExitCode::FAILURE
    }
}

/// Step 0 of `ci`, in-process: the diagnostic tables are split per area
/// (spec/diag.md §2.4), the per-WP Landed spec files are well formed
/// (spec/README.md "Landed sections"), no tracked file holds a local
/// absolute path (WP-1886) and the static-gap inventory is current. Each
/// reports every problem before failing.
fn ci_lints(root: &std::path::Path) -> bool {
    let mut ok = true;
    if let Err(problems) = diag_split::check(root) {
        for p in &problems {
            eprintln!("xtask ci: diag-split: {p}");
        }
        eprintln!("xtask ci: FAILED: run `cargo xtask diag-split` (spec/diag.md §2.4)");
        ok = false;
    }
    if let Err(problems) = landed::check(root) {
        for p in &problems {
            eprintln!("xtask ci: spec/landed: {p}");
        }
        eprintln!("xtask ci: FAILED: fix the files above (spec/README.md \"Landed sections\")");
        ok = false;
    }
    if let Err(problems) = local_paths::check(root) {
        for p in &problems {
            eprintln!("xtask ci: local-paths: {p}");
        }
        eprintln!(
            "xtask ci: FAILED: no tracked file may hold a local absolute path; write it \
             relative to the checkout or as a placeholder (spec/harness.md \"CI\", step 0)"
        );
        ok = false;
    }
    if let Err(problems) = static_gaps::check(root) {
        for p in &problems {
            eprintln!("xtask ci: static-gaps: {p}");
        }
        eprintln!(
            "xtask ci: FAILED: fix the sites or {} (spec/harness.md \"CI\", step 0)",
            static_gaps::INVENTORY
        );
        ok = false;
    }
    ok
}

/// One `cargo xtask test` run over the default corpus, with `compiler`
/// (`require_gcc`: `KILN_REQUIRE_GCC=1`; `shard`: `--shard K/N`;
/// `bmi`: `--bmi-kind`, and whether with `--bmi-image`).
fn ci_corpus(
    what: &str,
    compiler: Option<std::path::PathBuf>,
    require_gcc: bool,
    shard: Option<test::Shard>,
    bmi: Option<(u8, bool)>,
) -> test::CorpusOutcome {
    let shard_flag = shard.map_or_else(String::new, |s| format!(" --shard {s}"));
    eprintln!("xtask ci: cargo xtask test {what}{shard_flag}");
    let opts = test::Options {
        compiler,
        require_gcc,
        require_debuggers: test::require_debuggers_from_env(),
        require_sanitizer_runtime: test::require_sanitizer_runtime_from_env(),
        shard,
        bmi_kind: bmi.map(|(k, _)| k),
        bmi_image: bmi.is_some_and(|(_, image)| image),
        ..test::Options::default()
    };
    let start = std::time::Instant::now();
    let run = test::execute(&opts);
    if let Err(e) = &run {
        eprintln!("xtask test: error: {e}");
    }
    test::CorpusOutcome::of(&run, start.elapsed())
}

/// The directories `ci` runs the PCH differential over (spec/harness.md
/// "PCH differential"): the PCH tests and the module interfaces, a few
/// seconds.
const PCH_DIFF_SLICE: [&str; 2] =
    ["tests/conformance/cpp.include", "tests/conformance/module.interface"];

/// `cargo xtask test --compiler <kiln> --pch-diff <mode>` over
/// [`PCH_DIFF_SLICE`]; `snapshot` with `--pch-diff-require-restore` and
/// `--pch-diff-extra-dir` (WP-1403).
fn ci_pch_diff(
    kiln: &std::path::Path,
    mode: util::pch_diff::PchDiff,
    shard: Option<test::Shard>,
) -> test::CorpusOutcome {
    let shard_flag = shard.map_or_else(String::new, |s| format!(" --shard {s}"));
    let require = mode == util::pch_diff::PchDiff::Snapshot;
    eprintln!(
        "xtask ci: cargo xtask test --compiler {} --pch-diff {}{} {}{shard_flag}",
        kiln.display(),
        mode.as_str(),
        if require { " --pch-diff-require-restore --pch-diff-extra-dir" } else { "" },
        PCH_DIFF_SLICE.join(" ")
    );
    let root = test::repo_root();
    let opts = test::Options {
        compiler: Some(kiln.to_path_buf()),
        pch_diff: Some(mode),
        pch_require_restore: require,
        pch_extra_dir: require,
        shard,
        paths: PCH_DIFF_SLICE.iter().map(|d| root.join(d)).collect(),
        ..test::Options::default()
    };
    let start = std::time::Instant::now();
    let run = test::execute(&opts);
    if let Err(e) = &run {
        eprintln!("xtask test: error: {e}");
    }
    test::CorpusOutcome::of(&run, start.elapsed())
}

/// Runs `cargo <step>`, echoing its stderr while scanning it, and reruns it
/// once when it failed with `error[E0463]` ([`test::ci_should_retry`]). The
/// step is in the live-children table, so a SIGINT/SIGTERM to xtask stops
/// cargo and its rustc and test processes too ([`util::process::run_step`]).
fn ci_step(step: &[String]) -> bool {
    let shown = step.join(" ");
    let mut retried = false;
    loop {
        eprintln!("xtask ci: cargo {shown}");
        let start = std::time::Instant::now();
        let took = || format!("{:.1}s", start.elapsed().as_secs_f64());
        let mut cmd = std::process::Command::new(env!("CARGO"));
        cmd.args(step);
        let (status, stderr) = match util::process::run_step(&mut cmd, true) {
            Ok(r) => r,
            Err(e) => {
                eprintln!("xtask ci: could not run cargo {shown}: {e}");
                return false;
            }
        };
        if status.success() {
            eprintln!("xtask ci: cargo {shown}: ok in {}", took());
            return true;
        }
        if test::ci_should_retry(&stderr, retried) {
            eprintln!(
                "xtask ci: [retry] cargo {shown} failed with error[E0463] (can't find crate: an \
                 artifact vanished mid-build); rerunning it once"
            );
            retried = true;
            continue;
        }
        eprintln!("xtask ci: failed with {status} in {}", took());
        return false;
    }
}

