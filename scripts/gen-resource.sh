#!/usr/bin/env bash
# Regenerate kiln's resource/ directory from the clang 19 oracle.
#
#   resource/include/         clang 19 builtin headers (filtered copy)
#   resource/predefines/      `-E -dM` predefined-macro sets per (target, std)
#   resource/include-paths/   clang's C++ system include search order per target
#
# Idempotent: running it twice yields no diff. resource/include/LICENSE.TXT and
# resource/include/README.md are hand-maintained and are left untouched.
# See resource/README.md for what is produced and why.
#
# Usage: scripts/gen-resource.sh            (uses clang-19 / clang++-19 on PATH)
#        CLANG=/path/to/clang-19 CLANGXX=/path/to/clang++-19 scripts/gen-resource.sh
set -euo pipefail
export LC_ALL=C

WS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RES="$WS/resource"
CLANG="${CLANG:-clang-19}"
CLANGXX="${CLANGXX:-clang++-19}"

# ---- 0. Sanity: we import from exactly clang 19 ---------------------------------
major="$(echo __clang_major__ | "$CLANG" -E -P -x c - | tr -d '[:space:]')"
if [[ "$major" != 19 ]]; then
  echo "gen-resource: expected clang 19, $CLANG reports __clang_major__=$major" >&2
  exit 1
fi
SRC_INC="$("$CLANG" -print-resource-dir)/include"
[[ -f "$SRC_INC/stddef.h" ]] || { echo "gen-resource: no builtin headers in $SRC_INC" >&2; exit 1; }

TARGETS=(aarch64-unknown-linux-gnu x86_64-unknown-linux-gnu)
STDS=(c++17 c++20 c++23 c++26)

# ---- 1. Builtin headers ---------------------------------------------------------
# Excluded: anything not reachable/meaningful for a C/C++ build targeting
# Linux aarch64 or x86_64. Keep this list in sync with resource/include/README.md.
EXCLUDE_DIRS=(
  cuda_wrappers openmp_wrappers ppc_wrappers llvm_libc_wrappers zos_wrappers
  fuzzer orc profile sanitizer xray
)
EXCLUDE_FILES=(
  # CUDA / HIP offload
  '__clang_cuda_*' '__clang_hip_*'
  # OpenCL
  'opencl-c.h' 'opencl-c-base.h'
  # PowerPC
  'altivec.h' 'htmintrin.h' 'htmxlintrin.h'
  # SystemZ
  's390intrin.h' 'vecintrin.h'
  # Hexagon
  'hexagon_*' 'hvx_hexagon_protos.h'
  # LoongArch
  'larchintrin.h' 'lsxintrin.h' 'lasxintrin.h'
  # MIPS
  'msa.h'
  # RISC-V
  'riscv_*' 'sifive_vector.h'
  # NEC VE
  'velintrin*'
  # WebAssembly
  'wasm_simd128.h'
  # AArch32 M-profile only: #error unconditionally unless __ARM_FEATURE_MVE/CDE
  'arm_mve.h' 'arm_cde.h'
)

DST_INC="$RES/include"
mkdir -p "$DST_INC"
# Remove previously imported files (keep the hand-maintained ones).
find "$DST_INC" -mindepth 1 -type f ! -name LICENSE.TXT ! -name README.md -delete
find "$DST_INC" -mindepth 1 -type d -empty -delete

find_args=()
for d in "${EXCLUDE_DIRS[@]}"; do find_args+=( -path "./$d" -prune -o ); done
name_args=()
for f in "${EXCLUDE_FILES[@]}"; do name_args+=( ! -name "$f" ); done
(
  cd "$SRC_INC"
  find . "${find_args[@]}" -type f "${name_args[@]}" -print | sort | while read -r f; do
    mkdir -p "$DST_INC/$(dirname "$f")"
    cp -p "$f" "$DST_INC/$f"
    chmod 0644 "$DST_INC/$f"
  done
)
# Any kept header that #includes an excluded resource header would be broken.
# (Only report; #include_next and arch-guarded includes are legitimate.)
for f in "$DST_INC"/*.h; do
  grep -hoE '^[[:space:]]*#[[:space:]]*include[[:space:]]*[<"][^>"]+[>"]' "$f" || true
done | sed -E 's/.*[<"]([^>"]+)[>"]/\1/' | sort -u | while read -r inc; do
  if [[ -e "$SRC_INC/$inc" && ! -e "$DST_INC/$inc" ]]; then
    echo "gen-resource: note: a kept header #includes excluded '$inc'" >&2
  fi
done

# ---- 2. Predefined macros -------------------------------------------------------
DST_PRE="$RES/predefines"
mkdir -p "$DST_PRE"
find "$DST_PRE" -mindepth 1 -maxdepth 1 -type f -name '*.txt' -delete
dm() { # dm <target> <std>  -> sorted '#define NAME VALUE' lines on stdout
  "$CLANG" --target="$1" -std="$2" -E -dM -x c++ /dev/null | sort
}
for t in "${TARGETS[@]}"; do
  for s in "${STDS[@]}"; do
    dm "$t" "$s" > "$DST_PRE/$t.$s.txt"
  done
done

# Structure summary: what changes between stds, between targets, and strict vs GNU.
TMP="$(mktemp -d "${TMPDIR:-/tmp}/kiln-gen-resource.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
names() { sed -E 's/^#define ([A-Za-z0-9_]+).*/\1/' "$1"; }
udiff() { # udiff <label-a> <file-a> <label-b> <file-b>
  diff -U0 --label "$1" --label "$3" "$2" "$4" | grep -v '^@@' || true
}
{
  echo "# kiln resource/predefines structure summary. GENERATED by scripts/gen-resource.sh; do not edit."
  echo "# Oracle: $("$CLANG" --version | head -1)"
  echo "# Command: $CLANG --target=<triple> -std=<std> -E -dM -x c++ /dev/null | LC_ALL=C sort"
  echo "# Counts (number of macros):"
  for t in "${TARGETS[@]}"; do
    for s in "${STDS[@]}"; do
      printf '#   %-28s %-6s %s\n' "$t" "$s" "$(wc -l < "$DST_PRE/$t.$s.txt" | tr -d ' ')"
    done
  done
  echo "# -std=c++26 and -std=c++2c are byte-identical in clang 19 (both accepted)."
  echo
  echo "################################################################################"
  echo "# 1. Between standards, per target (consecutive pairs)"
  echo "################################################################################"
  for t in "${TARGETS[@]}"; do
    for ((i = 1; i < ${#STDS[@]}; i++)); do
      a="${STDS[i-1]}"; b="${STDS[i]}"
      echo; echo "## $t: $a -> $b"
      udiff "$t.$a.txt" "$DST_PRE/$t.$a.txt" "$t.$b.txt" "$DST_PRE/$t.$b.txt"
    done
  done
  echo
  echo "################################################################################"
  echo "# 2. Between targets, per standard (${TARGETS[0]} -> ${TARGETS[1]})"
  echo "################################################################################"
  first="${STDS[-1]}"
  udiff "${TARGETS[0]}.$first.txt" "$DST_PRE/${TARGETS[0]}.$first.txt" \
        "${TARGETS[1]}.$first.txt" "$DST_PRE/${TARGETS[1]}.$first.txt" > "$TMP/tdiff.$first"
  for s in "${STDS[@]}"; do
    udiff "${TARGETS[0]}.$s.txt" "$DST_PRE/${TARGETS[0]}.$s.txt" \
          "${TARGETS[1]}.$s.txt" "$DST_PRE/${TARGETS[1]}.$s.txt" > "$TMP/tdiff.$s"
  done
  for s in "${STDS[@]}"; do
    echo; echo "## $s: ${TARGETS[0]} -> ${TARGETS[1]}"
    if [[ "$s" != "$first" ]] && cmp -s <(sed 1,2d "$TMP/tdiff.$s") <(sed 1,2d "$TMP/tdiff.$first"); then
      echo "# (identical to the $first target diff below, modulo file labels)"
    else
      cat "$TMP/tdiff.$s"
    fi
  done
  echo
  echo "################################################################################"
  echo "# 3. Strict vs GNU dialect (-std=c++26 -> -std=gnu++26). Not stored as files;"
  echo "#    clang's DEFAULT is gnu++17, so a bare 'clang++ x.cpp' gets the GNU set."
  echo "################################################################################"
  for t in "${TARGETS[@]}"; do
    dm "$t" gnu++26 > "$TMP/$t.gnu++26.txt"
    echo; echo "## $t: c++26 -> gnu++26"
    udiff "$t.c++26.txt" "$DST_PRE/$t.c++26.txt" "$t.gnu++26.txt" "$TMP/$t.gnu++26.txt"
  done
  echo
  echo "################################################################################"
  echo "# 4. Macros that encode the clang version / vendor (what kiln claims to be)"
  echo "################################################################################"
  grep -hE '^#define (__clang|__VERSION__|__GNUC|__GXX_ABI_VERSION|__llvm__|__GNUG__|__GXX_)' \
    "$DST_PRE/${TARGETS[0]}.c++26.txt"
  echo
  echo "################################################################################"
  echo "# 5. Time/date/location-dependent builtins absent from -dM (must be supplied"
  echo "#    by the preprocessor itself). Checked against every generated file:"
  echo "################################################################################"
  for m in __DATE__ __TIME__ __TIMESTAMP__ __FILE__ __LINE__ __COUNTER__ \
           __INCLUDE_LEVEL__ __BASE_FILE__ __FILE_NAME__; do
    if grep -lqE "^#define $m( |$)" "$DST_PRE"/*.txt; then
      echo "#   $m: PRESENT in -dM output (unexpected)"
    else
      echo "#   $m: absent"
    fi
  done
} > "$DST_PRE/structure.diff"

# ---- 3. Include search order ----------------------------------------------------
DST_IP="$RES/include-paths"
mkdir -p "$DST_IP"
find "$DST_IP" -mindepth 1 -maxdepth 1 -type f -name '*.txt' -delete
for t in "${TARGETS[@]}"; do
  for lib in libstdc++ libc++; do
    out="$DST_IP/$t.txt"; [[ "$lib" == libc++ ]] && out="$DST_IP/$t.libc++.txt"
    {
      echo "# GENERATED by scripts/gen-resource.sh; do not edit."
      echo "# $CLANGXX --target=$t -stdlib=$lib -E -v -x c++ /dev/null"
      echo "# Oracle: $("$CLANGXX" --version | head -1)"
      echo "# Paths are verbatim (unnormalized) as clang prints them on this container;"
      echo "# '/usr/lib/llvm-19/lib/clang/19/include' is the resource dir -> kiln's resource/include."
      "$CLANGXX" --target="$t" -stdlib="$lib" -E -v -x c++ /dev/null -o /dev/null 2>"$TMP/v.txt"
      sed -n -e 's/^\(ignoring .*\)$/# \1/p' \
             -e '/search starts here:$/,/^End of search list\.$/p' "$TMP/v.txt"
      echo "# Driver -> cc1 classification (in order, including nonexistent dirs). Dirs passed"
      echo "# as -internal-externc-isystem are 'extern \"C\" system' dirs (C_ExternCSystem):"
      grep -m1 -- ' -cc1 ' "$TMP/v.txt" | tr ' ' '\n' |
        awk '/^-internal-(externc-)?isystem$/ { f = $0; next } f { print "#   " f " " $0; f = "" }'
    } > "$out"
  done
done

echo "gen-resource: done ($(du -sk "$RES" | cut -f1) KiB in resource/)"
