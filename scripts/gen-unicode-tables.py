#!/usr/bin/env python3
"""Generate crates/kiln_lex/src/unicode_tables.rs from the Unicode Character
Database (UAX #31 identifier properties and the NFC quick-check property).
NFC_QC=Maybe characters would need the full composition data; kiln does not
diagnose them yet (spec/lex.md, deviations).

Usage:  scripts/gen-unicode-tables.py [UCD_VERSION]   (default 15.1.0)

Downloads DerivedCoreProperties.txt and DerivedNormalizationProps.txt for the
given version from unicode.org (into a temporary directory), extracts
XID_Start, XID_Continue and NFC_QC=No, merges adjacent ranges
and writes sorted `(lo, hi)` inclusive range tables. The version default
matches clang 19, kiln's conformance oracle.
"""
import os
import sys
import tempfile
import urllib.request

VERSION = sys.argv[1] if len(sys.argv) > 1 else "15.1.0"
BASE = f"https://www.unicode.org/Public/{VERSION}/ucd/"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "crates", "kiln_lex", "src", "unicode_tables.rs")


def fetch(name, tmp):
    path = os.path.join(tmp, name)
    with urllib.request.urlopen(BASE + name) as r, open(path, "wb") as f:
        f.write(r.read())
    return path


def parse(path, want):
    """Return {key: [(lo, hi)]} for lines whose property (and value) match."""
    out = {k: [] for k in want}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(";")]
            key = tuple(fields[1:])
            if key not in out:
                continue
            cps = fields[0].split("..")
            lo = int(cps[0], 16)
            hi = int(cps[-1], 16)
            out[key].append((lo, hi))
    return out


def merge(ranges):
    ranges = sorted(ranges)
    merged = []
    for lo, hi in ranges:
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
        else:
            merged.append((lo, hi))
    return merged


def emit(f, name, doc, ranges):
    f.write(f"/// {doc}\n")
    f.write(f"pub(crate) static {name}: &[(u32, u32)] = &[\n")
    for lo, hi in ranges:
        f.write(f"    (0x{lo:04X}, 0x{hi:04X}),\n")
    f.write("];\n\n")


def main():
    with tempfile.TemporaryDirectory() as tmp:
        core = parse(fetch("DerivedCoreProperties.txt", tmp),
                     [("XID_Start",), ("XID_Continue",)])
        norm = parse(fetch("DerivedNormalizationProps.txt", tmp),
                     [("NFC_QC", "N")])
    # ASCII is handled by hand-written fast paths in the lexer.
    def non_ascii(rs):
        return [(max(lo, 0x80), hi) for lo, hi in merge(rs) if hi >= 0x80]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// @generated by scripts/gen-unicode-tables.py from the Unicode Character\n")
        f.write(f"// Database {VERSION}. Do not edit by hand; re-run the script.\n\n")
        f.write(f"/// The UCD version these tables were generated from.\n")
        f.write(f"pub(crate) const UNICODE_VERSION: &str = \"{VERSION}\";\n\n")
        emit(f, "XID_START", "UAX #31 `XID_Start`, non-ASCII code points only.",
             non_ascii(core[("XID_Start",)]))
        emit(f, "XID_CONTINUE", "UAX #31 `XID_Continue`, non-ASCII code points only.",
             non_ascii(core[("XID_Continue",)]))
        emit(f, "NFC_QC_NO", "`NFC_Quick_Check=No`: never appears in NFC text.",
             merge(norm[("NFC_QC", "N")]))


main()
