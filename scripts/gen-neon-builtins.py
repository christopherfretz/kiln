#!/usr/bin/env python3
"""Generate crates/kiln_ast/src/neon_builtins.rs, the AArch64 NEON / FP16
builtin table (spec/sema-builtins.md "Target builtins", WP-558).

The table holds every `__builtin_neon_*` name that kiln's resource headers
`arm_neon.h` and `arm_fp16.h` (clang 19's) reference, sorted by name, with
clang's `Builtins.td`-notation prototype, its attribute string and its
required target features (clang `TARGET_BUILTIN`). Prototypes and features
come from a clang >= 21 build's generated `arm_neon.inc` / `arm_fp16.inc`
(string-table format); the names clang 21 dropped are listed in
CLANG19_ONLY below with the types `clang++-19 -Xclang -ast-dump` gives them.
With `--check`, `clang++-19 -E` is run to confirm that `__has_builtin`
answers 1 for every row under the `-march=` its features name and 0 under
the default `armv8-a` unless the row needs only `neon`.

Usage: scripts/gen-neon-builtins.py <clang-build>/tools/clang/include/clang/Basic [--check]
"""

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "crates/kiln_ast/src/neon_builtins.rs"
HEADERS = ["arm_neon.h", "arm_fp16.h"]

# Names clang 19 declares that clang 21's tables no longer carry.
CLANG19_ONLY = {
    "__a64_vcvtq_low_bf16_f32": ("V16ScV16Sci", "n", "bf16,neon"),
    "vcmla_f64": ("V8ScV8ScV8ScV8Sci", "n", "v8.3a,neon"),
    "vcmla_rot90_f64": ("V8ScV8ScV8ScV8Sci", "n", "v8.3a,neon"),
    "vcmla_rot180_f64": ("V8ScV8ScV8ScV8Sci", "n", "v8.3a,neon"),
    "vcmla_rot270_f64": ("V8ScV8ScV8ScV8Sci", "n", "v8.3a,neon"),
}

ROW = re.compile(
    r"StrOffsets\{\d+ /\* (\S+) \*/, \d+ /\* (.*?) \*/, \d+ /\* (.*?) \*/, \d+ /\* (.*?) \*/\}"
)

EXT = {"fullfp16": "fp16"}


def march(features):
    fs = [f for f in features.split(",") if f != "neon"]
    ver = [f for f in fs if f.startswith("v8.")]
    base = "armv8-a" if not ver else "armv" + max(ver)[1:-1] + "-a"
    return base + "".join("+" + EXT.get(f, f) for f in fs if not f.startswith("v8."))


def check(rows):
    groups = {}
    for name, (_, _, feats) in rows.items():
        groups.setdefault(feats, []).append(name)
    tmp = OUT.parent / "neon_probe.tmp.cpp"
    bad = 0
    try:
        for feats, names in sorted(groups.items()):
            tmp.write_text("".join(f"{n} __has_builtin(__builtin_neon_{n})\n" for n in names))
            for m, want in ((march(feats), "1"), ("armv8-a", "1" if feats == "neon" else "0")):
                out = subprocess.run(
                    ["clang++-19", "-E", "-P", "-x", "c++", str(tmp), "-march=" + m],
                    capture_output=True, text=True, check=True,
                ).stdout.split()
                got = dict(zip(out[::2], out[1::2]))
                for n in names:
                    if got.get(n) != want:
                        print(f"mismatch: {n} under -march={m}: {got.get(n)} != {want}")
                        bad += 1
    finally:
        tmp.unlink(missing_ok=True)
    return bad


def main():
    inc_dir = pathlib.Path(sys.argv[1])
    inc = {}
    for f in ("arm_neon.inc", "arm_fp16.inc"):
        for name, proto, attrs, feats in ROW.findall((inc_dir / f).read_text()):
            inc[name] = (proto, attrs, feats)
    inc.update(CLANG19_ONLY)
    used = set()
    for h in HEADERS:
        used |= set(re.findall(r"__builtin_neon_(\w+)", (ROOT / "resource/include" / h).read_text()))
    missing = sorted(used - inc.keys())
    if missing:
        sys.exit(f"no prototype for: {missing}")
    rows = {n: inc[n] for n in used}
    for n, (proto, attrs, _) in rows.items():
        if attrs != "n":
            sys.exit(f"unexpected attributes {attrs!r} for {n}")
        if not re.fullmatch(r"(?:[ISUWL]|V\d+)*[vcsifdhy][C*]*(?:(?:[ISUWL]|V\d+)*[vcsifdhy][C*]*)*", proto):
            sys.exit(f"unexpected prototype {proto!r} for {n}")
    if "--check" in sys.argv[2:] and check(rows):
        sys.exit("clang++-19 disagrees")
    lines = [
        "// @generated by scripts/gen-neon-builtins.py from clang's arm_neon.inc /",
        "// arm_fp16.inc (clang 19's names: those resource/include/arm_neon.h and",
        "// arm_fp16.h reference). Do not edit.",
        "",
        "use crate::decl::builtin::neon::r;",
        "use crate::decl::builtin::neon::Row;",
        "",
        "/// Every AArch64 NEON / FP16 builtin, sorted by name: (name, prototype,",
        "/// required target features).",
        "#[rustfmt::skip]",
        "pub(crate) const NEON: &[Row] = &[",
    ]
    for i, n in enumerate(sorted(rows, key=lambda n: "__builtin_neon_" + n)):
        proto, _, feats = rows[n]
        lines.append(f'    r({i}, "__builtin_neon_{n}", "{proto}", "{feats}"),')
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} builtins")


if __name__ == "__main__":
    main()
