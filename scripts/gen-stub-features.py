#!/usr/bin/env python3
# STUB(WP-015): generates crates/kiln_driver/src/stub_features_table.rs, the
# answers clang 19 gives to every __has_builtin / __has_feature /
# __has_extension / __has_attribute / __has_cpp_attribute /
# __has_declspec_attribute / __has_constexpr_builtin query that appears in the
# libc++ 19 headers (directly or through glibc's __glibc_has_* wrappers), the sysroot headers, kiln's resource headers and tests/.
# This is a stopgap until WP-015 lands the real feature tables; delete both
# files then.
#
# usage: scripts/gen-stub-features.py   (from the repo root; needs clang++-19)
import os, re, subprocess, sys

ROOTS = ["/usr/lib/llvm-19/include/c++/v1", "/usr/include", "resource/include", "tests"]
KINDS = ["has_builtin", "has_feature", "has_extension", "has_attribute",
         "has_cpp_attribute", "has_declspec_attribute", "has_constexpr_builtin"]
# glibc wraps the queries in __glibc_has_{attribute,builtin,extension}.
pat = re.compile(rb"(?:__|__glibc_)(" + b"|".join(k.encode() for k in KINDS) + rb")\s*\(\s*([A-Za-z_][A-Za-z_0-9]*(?:::[A-Za-z_][A-Za-z_0-9]*)?)")
items = set()
for root in ROOTS:
    for d, _, fs in os.walk(root):
        for f in fs:
            try:
                data = open(os.path.join(d, f), "rb").read()
            except OSError:
                continue
            for m in pat.finditer(data):
                items.add((m.group(1).decode(), m.group(2).decode()))
# libc++'s __has_keyword(x) is !__is_identifier(x).
kw = re.compile(rb"__(?:has_keyword|is_identifier)\s*\(\s*([A-Za-z_][A-Za-z_0-9]*)\s*\)")
for root in ROOTS:
    for d, _, fs in os.walk(root):
        for f in fs:
            try:
                data = open(os.path.join(d, f), "rb").read()
            except OSError:
                continue
            for m in kw.finditer(data):
                items.add(("is_identifier", m.group(1).decode()))
items = sorted(items)

def query(args, lang):
    src = "".join(f"R{i} __{k}({n})\n" for i, (k, n) in enumerate(items))
    p = subprocess.run(["clang++-19", *args, "-x", lang, "-E", "-P", "-"],
                       input=src, capture_output=True, text=True)
    out = {}
    for line in p.stdout.splitlines():
        m = re.match(r"\s*R(\d+) (.*)", line)
        if m:
            v = m.group(2).strip().rstrip("L")
            out[int(m.group(1))] = int(v) if v.isdigit() else 0
    return out

target = "--target=aarch64-unknown-linux-gnu"
cxx = query([target, "-std=c++26"], "c++")
c = query([target, "-std=c17"], "c")
lines = [
    "// GENERATED by scripts/gen-stub-features.py; do not edit.",
    "// STUB(WP-015): clang 19's answers (aarch64; C++26 and C17) to the feature",
    "// queries found in the libc++ 19, sysroot and resource headers and tests/.",
    "",
    "/// `(query, name, C++ value, C value)`, sorted by query then name.",
    "pub(crate) const TABLE: &[(&str, &str, u32, u32)] = &[",
]
for i, (k, n) in enumerate(items):
    lines.append(f'    ("{k}", "{n}", {cxx.get(i, 0)}, {c.get(i, 0)}),')
lines.append("];")
open("crates/kiln_driver/src/stub_features_table.rs", "w").write("\n".join(lines) + "\n")
print(f"{len(items)} queries", file=sys.stderr)
